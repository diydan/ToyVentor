// Describe & build: the recipe validator that runs in the browser (and in the endpoint). See kip-describe-contract.md, "Legal means".
//
// It checks what can be known from the connector data alone: structure, that parts and connectors exist, that the two connectors of a mate are a legal
// pair in the fit matrix, that cells and fields suit the connector kind. It answers in plain language and, where it can, names a legal alternative.
// It can NOT see geometry: whether the finished parts collide is decided by the real validator (the endpoint runs it and marks the reply `validated`).
// Data comes from kip-describe-parts.json, generated by tools/build_parts_data.py.

const STACK = new Set(['studs', 'sockets']);
const AXIS = new Set(['pin', 'bore']);
const ID_RE = /^[A-Za-z0-9_]{1,24}$/;
const ANCHORS = ['start', 'center', 'end'];

export async function loadPartsData(url = '/kip/kip-describe-parts.json', fetchImpl = globalThis.fetch) {
  const res = await fetchImpl(url);
  if (!res.ok) throw new Error(`parts data ${url} returned ${res.status}`);
  return indexPartsData(await res.json());
}

/** Add the lookup the checks need: connector -> group id. */
export function indexPartsData(doc) {
  const groupOf = new Map();
  for (const [gid, g] of Object.entries(doc.groups)) for (const m of g.members) groupOf.set(m, gid);
  return { ...doc, groupOf };
}

const human = (id) => String(id).replace(/_/g, ' ');
const nice = (data, part) => data.parts[part]?.label?.toLowerCase() ?? human(part);

/** Can connector a (on partA) mate with connector b (on partB) according to the fit matrix? */
export function legalPair(data, partA, connA, partB, connB) {
  const ga = data.groupOf.get(`${partA}.${connA}`), gb = data.groupOf.get(`${partB}.${connB}`);
  return Boolean(ga && gb && data.groups[ga].mates.includes(gb));
}

function connectorsThatFit(data, part, kindClass, mateWith) {
  const out = [];
  for (const [id, c] of Object.entries(data.parts[part].connectors)) {
    if (!kindClass.has(c.kind)) continue;
    if (mateWith ? legalPair(data, part, id, mateWith.part, mateWith.conn) : true) out.push(id);
  }
  return out;
}

const cellProblem = (c, cell) => {
  if (!Array.isArray(cell) || cell.length !== 2 || !cell.every(Number.isInteger)) return 'must be two whole numbers, [column, row]';
  const [nx, ny] = c.grid ?? [1, 1];
  if (cell[0] < 0 || cell[1] < 0 || cell[0] >= nx || cell[1] >= ny) return `is outside its ${nx} by ${ny} grid`;
  if ((c.omit ?? []).some((o) => o[0] === cell[0] && o[1] === cell[1])) return 'has no connector at that cell';
  return null;
};

/**
 * Validate steps against the part data. Returns { ok, errors } where each error is
 *   { step: <id or index>, index, code, message, suggestion? }
 * `options.allowedIds` (the request's list) is optional. Every problem is reported, not just the first.
 */
export function validateRecipe(steps, data, { allowedIds } = {}) {
  const errors = [];
  const add = (index, code, message, suggestion) => errors.push({ step: steps[index]?.id ?? index, index, code, message, ...(suggestion ? { suggestion } : {}) });
  if (!Array.isArray(steps) || !steps.length) return { ok: false, errors: [{ step: 0, index: 0, code: 'no_steps', message: 'The recipe has no steps.' }] };

  const firstIndex = new Map();
  steps.forEach((s, i) => { if (typeof s?.id === 'string' && !firstIndex.has(s.id)) firstIndex.set(s.id, i); });
  const seen = new Set();

  steps.forEach((s, i) => {
    const n = i + 1;
    if (!s || typeof s !== 'object' || typeof s.id !== 'string' || !ID_RE.test(s.id)) return add(i, 'bad_field', `Step ${n} needs an id of letters, numbers and underscores (up to 24).`);
    if (seen.has(s.id)) add(i, 'duplicate_id', `Step ${n} reuses the id "${s.id}"; every step needs its own.`);
    const part = data.parts[s.part];
    if (!part) add(i, 'unknown_part', `Step ${n} uses "${s.part}", which is not a part we have.`);
    else if (allowedIds && !allowedIds.includes(s.part)) add(i, 'not_allowed', `The ${nice(data, s.part)} is not in the parts list for this build.`);

    if (i === 0) {
      if (s.mate !== undefined) add(i, 'unexpected_mate', 'The first step is the base, so it cannot plug into anything.');
    } else if (s.mate === undefined) {
      add(i, 'missing_mate', `Step ${n} (${part ? nice(data, s.part) : s.id}) does not say what it plugs into.`);
    } else if (part) {
      checkMate(s, i, part);
    }
    seen.add(s.id);
  });

  function checkMate(s, i, part) {
    const n = i + 1, m = s.mate, what = nice(data, s.part);
    if (!m || typeof m !== 'object' || Array.isArray(m)) return add(i, 'bad_field', `Step ${n} (${what}) has a malformed mate.`);
    for (const k of ['conn', 'host', 'hostConn']) if (typeof m[k] !== 'string' || !m[k]) return add(i, 'bad_field', `Step ${n} (${what}) mate needs "${k}".`);
    const hostIndex = firstIndex.get(m.host);
    if (hostIndex === undefined) return add(i, 'unknown_host', `Step ${n} (${what}) plugs into "${m.host}", but there is no such step.`);
    if (hostIndex >= i) return add(i, 'host_after_step', `Step ${n} (${what}) plugs into a part that is only added later; put the host first.`);
    const hostPart = steps[hostIndex].part;
    const host = data.parts[hostPart];
    if (!host) return;   // already reported on the host's own step
    const hostWhat = nice(data, hostPart);
    const c = part.connectors[m.conn], hc = host.connectors[m.hostConn];
    if (!c) return add(i, 'unknown_connector', `The ${what} has no "${human(m.conn)}" connector.`, `The ${what} has: ${Object.keys(part.connectors).map(human).join(', ')}.`);
    if (!hc) return add(i, 'unknown_connector', `The ${hostWhat} has no "${human(m.hostConn)}" connector.`, `The ${hostWhat} has: ${Object.keys(host.connectors).map(human).join(', ')}.`);

    const stack = STACK.has(c.kind);
    if (stack !== STACK.has(hc.kind)) {
      return add(i, 'kind_mismatch', `The ${what}'s ${human(m.conn)} (${c.kind}) cannot join the ${hostWhat}'s ${human(m.hostConn)} (${hc.kind}); studs go with sockets and pins with holes.`,
        fitHint(what, hostWhat, hostPart, c, s.part, m.conn));
    }
    if (!legalPair(data, s.part, m.conn, hostPart, m.hostConn)) {
      add(i, 'no_legal_pair', `The ${what}'s ${human(m.conn)} cannot plug into the ${hostWhat}'s ${human(m.hostConn)}.`, fitHint(what, hostWhat, hostPart, c, s.part, m.conn));
    }

    const allowedKeys = stack ? ['conn', 'host', 'hostConn', 'cell', 'hostCell', 'rot'] : ['conn', 'host', 'hostConn', 'along', 'hostCell'];
    const extra = Object.keys(m).filter((k) => !allowedKeys.includes(k));
    if (extra.length) add(i, 'bad_field', `Step ${n} (${what}): ${extra.join(', ')} ${extra.length > 1 ? 'do' : 'does'} not apply to a ${stack ? 'stud and socket' : 'pin and hole'} mate.`);
    if (m.cell !== undefined && stack) { const p = cellProblem(c, m.cell); if (p) add(i, 'cell_out_of_range', `Step ${n} (${what}): the cell ${p}.`); }
    if (m.hostCell !== undefined) { const p = cellProblem(hc, m.hostCell); if (p) add(i, 'cell_out_of_range', `Step ${n} (${what}): the host cell ${p}.`); }
    if (m.rot !== undefined && stack && !(Number.isInteger(m.rot) && m.rot >= 0 && m.rot <= 3)) add(i, 'bad_field', `Step ${n} (${what}): rot must be 0, 1, 2 or 3 quarter turns.`);
    if (m.along !== undefined && !stack && !(typeof m.along === 'number' && Number.isFinite(m.along)) && !ANCHORS.includes(m.along)) add(i, 'bad_field', `Step ${n} (${what}): along must be ${ANCHORS.join(', ')} or a number.`);
  }

  function fitHint(what, hostWhat, hostPart, c, part, conn) {
    const cls = STACK.has(c.kind) ? STACK : AXIS;
    const onHost = connectorsThatFit(data, hostPart, cls, { part, conn });
    if (onHost.length) return `The ${what}'s ${human(conn)} can go into the ${hostWhat}'s ${onHost.slice(0, 3).map(human).join(' or ')}.`;
    return `Nothing on the ${hostWhat} takes the ${what}'s ${human(conn)}; try a different part.`;
  }

  return { ok: errors.length === 0, errors };
}

/**
 * Plain-language form of an error from the real validator (tools/validate_worker.py): { code, detail, steps } -> { step, code, message, detail }.
 * `detail` is kept as is for logs and for the model's retry prompt; `message` is what a grown-up reads.
 */
export function explainValidatorError(err, steps, data) {
  const byId = new Map((steps ?? []).map((s) => [s.id, s]));
  const name = (id) => (byId.get(id) ? nice(data, byId.get(id).part) : String(id));
  const [a, b] = err.steps ?? [];
  let message;
  switch (err.code) {
    case 'collision':
      message = a && b ? `The ${name(a)} (step "${a}") and the ${name(b)} (step "${b}") would be in the same space.` : 'Two parts would be in the same space.';
      break;
    case 'floating':
      message = a ? `The ${name(a)} (step "${a}") is not attached to the rest of the build.` : 'A part is not attached to the rest of the build.';
      break;
    case 'profile_mismatch':
      message = 'A pin does not fit the hole it was given (the shapes differ).';
      break;
    case 'size_mismatch':
      message = 'Two parts are different sizes and do not fit together.';
      break;
    case 'misaligned':
      message = 'Two parts that should line up do not.';
      break;
    case 'cannot_place':
      message = 'Two parts cannot be fitted together the way the recipe says.';
      break;
    default:
      message = 'This combination of parts does not work.';
  }
  return { step: a ?? 0, code: err.code, message, detail: err.detail, steps: err.steps ?? [] };
}

/** One sentence for a grown-up from a list of errors (the first few). */
export function describeProblems(errors, max = 3) {
  return errors.slice(0, max).map((e) => e.message).join(' ') + (errors.length > max ? ` (and ${errors.length - max} more)` : '');
}
