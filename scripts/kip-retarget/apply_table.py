#!/usr/bin/env python3
"""Write the PROP_ARMS table into kip-clips.js from one or more retarget.mjs output files: python3 apply_table.py out1.json [out2.json ...]"""
import json, re, sys, glob
if len(sys.argv) < 2 or sys.argv[1].startswith('-'):
    sys.exit(__doc__)
from pathlib import Path
HERE=Path(__file__).resolve().parent
r={}
for f in sys.argv[1:]:        # the retarget output files, later ones win
    r.update(json.load(open(f)))
order=['prop_broom','prop_mop','prop_scrub_brush','prop_vacuum','prop_upright_vacuum','prop_spatula','prop_frying_pan','prop_paint_roller','prop_hammer','prop_screwdriver','prop_wrench','prop_guitar','prop_trumpet','prop_maracas','prop_flag','prop_magnifier']
def arr(a): return '['+','.join(str(x) for x in a)+']'
lines=["// GENERATED by the arm retargeter (scripts/kip-retarget/, see the note above PROP_ARMS). Do not edit by hand.",
       "// Per prop clip: `flip` (mount the prop end for end, so a head-up prop gets a thumb-up hand), then 36 samples per loop of the right arm",
       "// [rx, ry, rz], the elbow rx and the hand [rx, ry, rz], in degrees (the same Euler order as every other joint).",
       "const PROP_ARMS = {"]
for cid in order:
    v=r[cid]
    lines.append(f"  {cid}: {{ flip: {'true' if v['flip'] else 'false'},")
    lines.append("    arm: ["+','.join(arr(a) for a in v['arm'])+"],")
    lines.append("    fore: "+arr(v['fore'])+",")
    lines.append("    hand: ["+','.join(arr(a) for a in v['hand'])+"] },")
lines.append("};")
p=str(HERE.parent.parent/'parts'/'kip'/'viewer'/'kip-clips.js')
s=open(p).read()
a=s.index("// GENERATED by the arm retargeter")
b=s.index("\n};\n", s.index("const PROP_ARMS = {"))+4
open(p,'w').write(s[:a]+'\n'.join(lines)+'\n'+s[b:])
print('merged', [k for k in order if k in r], 'flips', [k for k in order if r[k]['flip']])
