/**
 * The tracked record of every evaluated run: reads scripts/tuning/data/eval-<label>.json (generated, git-ignored, the per-wish outputs) and writes the SMALL, committable summary
 * scripts/tuning/results/pilots.json and pilots.md: one row per run with every number the decision rule uses, and the rule's verdict against the base run.
 *
 *   npm run tune:results            (after every `eval.ts run`; rerunning rewrites both files from whatever eval files exist)
 *
 * This is where progress is tracked in the repo: the table says which runs exist and what they scored; docs/product/journal.md carries the story, scripts/tuning/MODEL_CARD.md the claims, and
 * scripts/tuning/results/LEDGER.md the GPU spend. A run is listed only if its eval file exists, so a run that died or never started is not in the table (the journal says what happened to it).
 */
import { fileURLToPath } from "node:url";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { decide, scoreRedteam, scoreRun, type EvalResult, type Report } from "./lib/compare";
const HERE = fileURLToPath(new URL(".", import.meta.url));
const DATA = join(HERE, "data");
const OUT = join(HERE, "results");

const load = (label: string): Report & { at?: string } => {
  const d = JSON.parse(readFileSync(join(DATA, `eval-${label}.json`), "utf8")) as { label: string; at?: string; results: EvalResult[] };
  return { label, at: d.at, metrics: scoreRun(d.results), redteam: scoreRedteam(d.results) };
};

const labels = readdirSync(DATA).filter((f) => /^eval-.+\.json$/.test(f)).map((f) => f.slice(5, -5)).sort((a, b) => (a === "base" ? -1 : b === "base" ? 1 : a.localeCompare(b)));
if (!labels.includes("base")) throw new Error("no eval-base.json: every verdict is against the base run (npm run tune:eval -- run --label base)");
const reports = labels.map(load);
const base = reports[0]!;

const rows = reports.map((r) => {
  const d = r.label === "base" ? null : decide(base, r, "both");
  return {
    label: r.label,
    at: r.at,
    metrics: r.metrics,
    redteam: { passed: r.redteam.passed, total: r.redteam.total, brand: r.redteam.byKind["brand"], unsafe: r.redteam.byKind["unsafe"], inject: r.redteam.byKind["inject"] },
    verdict: d ? (d.pass ? "PASS (goal both)" : "DO NOT SHIP (goal both)") : "baseline",
    failedChecks: d ? d.checks.filter((c) => !c.ok).map((c) => c.name) : [],
  };
});

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, "pilots.json"), JSON.stringify({ about: "generated by scripts/tuning/results.ts from scripts/tuning/data/eval-*.json; do not edit by hand", runs: rows }, null, 2) + "\n");

const cell = (f: (x: (typeof rows)[number]) => string) => rows.map(f).join(" | ");
const md = `# Evaluated runs (generated by \`npm run tune:results\`; do not edit)

Every run: the same wishes, Worker, optimizer daemon and gates. Verdicts are the decision rule (\`lib/compare.ts\`) against the base run, goal "both". The red-team set is a seed: one brand wish moves "brand" by about 5 points.

| | ${rows.map((r) => r.label).join(" | ")} |
| --- | ${rows.map(() => "---").join(" | ")} |
| wishes scored | ${cell((r) => String(r.metrics.n))} |
| printable | ${cell((r) => `${r.metrics.printablePct}%`)} |
| printable on the first call | ${cell((r) => `${r.metrics.firstCallPct}%`)} |
| mean calls | ${cell((r) => String(r.metrics.meanCalls))} |
| median / p90 seconds | ${cell((r) => `${r.metrics.p50} / ${r.metrics.p90}`)} |
| answers the name filters fixed | ${cell((r) => `${r.metrics.filterFired} (${r.metrics.filterFiredPct}%)`)} |
| no answer | ${cell((r) => String(r.metrics.noAnswer))} |
| red-team passed | ${cell((r) => `${r.redteam.passed}/${r.redteam.total}`)} |
| red-team brand | ${cell((r) => `${r.redteam.brand?.passed}/${r.redteam.brand?.total}`)} |
| red-team unsafe, injection | ${cell((r) => `${r.redteam.unsafe?.passed}/${r.redteam.unsafe?.total}, ${r.redteam.inject?.passed}/${r.redteam.inject?.total}`)} |
| leaks / unsafe / brand text in output | ${cell((r) => `${r.metrics.leaks} / ${r.metrics.unsafeInOutput} / ${r.metrics.brandInOutput}`)} |
| decision rule | ${cell((r) => r.verdict)} |

Failed checks: ${rows.filter((r) => r.failedChecks.length).map((r) => `\n- **${r.label}**: ${r.failedChecks.join("; ")}`).join("") || "none"}
`;
writeFileSync(join(OUT, "pilots.md"), md);
console.log(`wrote ${join(OUT, "pilots.md")} and pilots.json for ${labels.join(", ")}`);
if (!existsSync(join(OUT, "LEDGER.md"))) console.log("note: scripts/tuning/results/LEDGER.md (the GPU spend ledger) is not there yet");
