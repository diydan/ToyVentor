// Writes src/features/game/world/runtime/wishWorlds.data.ts from the showcase worlds' stored briefs (docs/mockups/generated-backdrops/looks/<id>/brief.json, made by scripts/generate-world-art.ts) and the art baked into
// runtime/assets/looks/ (python3 scripts/make-backdrops.py looks). Each world gets a DETERMINISTIC look id (gen- and the first ten hex digits of the SHA-1 of its showcase id) so the art key never changes between runs.
//
//   npx tsx scripts/bake-wish-worlds.ts
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SHOWCASE } from "./lib/world-showcase";
import { buildLook, parseBrief } from "../shared/worldBrief";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOOKS = path.join(ROOT, "docs", "mockups", "generated-backdrops", "looks");
const ASSETS = path.join(ROOT, "src", "features", "game", "world", "runtime", "assets", "looks");
const OUT = path.join(ROOT, "src", "features", "game", "world", "runtime", "wishWorlds.data.ts");

const camel = (id: string) => id.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
const imports: string[] = [];
const rows: string[] = [];
for (const job of SHOWCASE) {
  const briefFile = path.join(LOOKS, job.id, "brief.json");
  if (!existsSync(briefFile)) { console.log(`skipped ${job.id}: no brief`); continue; }
  const parsed = parseBrief(JSON.parse(readFileSync(briefFile, "utf8")), { base: job.base, safe: () => true });
  if (!parsed.ok) { console.log(`skipped ${job.id}: stored brief no longer validates (${parsed.reason})`); continue; }
  const id = "gen-" + createHash("sha1").update(job.id).digest("hex").slice(0, 10);
  const look = buildLook(parsed.brief, job.base, id);
  const pieces = (["far-day", "far-night", "mid"] as const).map((p) => ({ p, file: path.join(ASSETS, `${job.id}-${p}.webp`), name: `${camel(job.id)}${p.split("-").map((w) => w[0]!.toUpperCase() + w.slice(1)).join("")}` }));
  let art = "null";
  if (look.kind === "outdoor") {
    if (!pieces.every((x) => existsSync(x.file))) { console.log(`skipped ${job.id}: art not baked`); continue; }
    for (const x of pieces) imports.push(`import ${x.name} from "./assets/looks/${job.id}-${x.p}.webp?url";`);
    look.art = { farDay: true, farNight: true, mid: true };
    art = `{ farDay: ${pieces[0]!.name}, farNight: ${pieces[1]!.name}, mid: ${pieces[2]!.name} }`;
  }
  rows.push(`  { id: ${JSON.stringify(job.id)}, wish: ${JSON.stringify(job.wish)}, base: ${JSON.stringify(job.base)}, look: ${JSON.stringify(look)} as WorldLook, art: ${art} },`);
  console.log(`${job.id}: ${look.id} "${look.name}" (${look.kind})`);
}
writeFileSync(OUT, `// GENERATED by scripts/bake-wish-worlds.ts from the showcase worlds' stored briefs and baked art. Do not edit by hand: re-run it.
// (docs/specs/generated-worlds-spec.md section 0: the showcase worlds, made offline with the same brief and image code the live route uses.)
import type { Base, WorldLook } from "../../../../../shared/worldBrief";
${imports.join("\n")}

export interface WishData { id: string; wish: string; base: Base; look: WorldLook; art: { farDay: string; farNight: string; mid: string } | null }

export const WISH_DATA: WishData[] = [
${rows.join("\n")}
];
`);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${rows.length} worlds`);
