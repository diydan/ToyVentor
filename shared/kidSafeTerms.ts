/**
 * Unsafe-term check for text a child types or a model returns, in the seven languages the product speaks (en, es, fr, de, it, pt, tr). Pure: no DOM, no clock, no network.
 * Drafted 2026-11-04 after the child-safety review found that the old check was English only (docs/specs/forge-ai-spec.md, "Child safety", gap 1). It answers "does this text
 * contain a word the product should not show or act on?"; it is a backstop, never the only guard (the model's own safety training, the narrow output channel and the gates
 * come first, and a classifier is still to be added).
 *
 * TWO TIERS, each a list per language:
 *  - `age`: the age-fit words (kill, blood, gun, knife, weapon, drugs, alcohol, war, nudity ...). "scary" and its translations are NOT on it: Dan decided on 2026-11-04 that a child may ask for
 *    a scary monster (haunt*, horror and nightmare* are still refused: a separate decision, not yet made). English is the list the product already used, unchanged.
 *    The other six are a hand translation of those same words and are UNREVIEWED by a native speaker.
 *  - `severe`: obscenities and slurs, from the open LDNOOBW lists (CC BY 4.0) with the words a child can plausibly type removed (shared/kidSafeTermsSevere.ts is generated by
 *    scripts/gen-kid-safe-terms.ts, which lists every exception and the reason).
 *
 * HOW IT MATCHES (and why not `\\b` and a lowercased copy): see shared/kidSafeNormalize.ts. Whole words only (an entry ending in `*` also matches any letters after it, for
 * inflections), accents folded for every language except Turkish, which keeps its letters, and a second look with digits and symbols read as letters ("k1ll").
 * The language of a wish is NOT known, so every language's lists are checked against every text. That is why short single words are not on the severe lists ("con" is rude in
 * French and "with" in Spanish) and why tests/fixtures/kid-wishes.json holds harmless wishes in all seven languages that must never be refused.
 *
 * KNOWN LIMITS (tested, so that nobody assumes otherwise): letters spaced apart ("k i l l"), words glued together, misspellings other than digits for letters, any language
 * outside the seven, and Turkish typed without its special letters. Lists catch words, not meaning: "a hat that hurts people" passes.
 *
 * OWNER: Dan decides what goes on the lists (policy per age band is still to be written). Change a list here, add a fixture line for every word a real child's wish was refused
 * for, and run tests/kid-safe-terms.test.ts.
 */
