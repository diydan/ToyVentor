export interface TermHit {
  lang: TermLang;
  tier: Tier;
  /** The text that matched, for tests and for a reviewer. Never log it: it is what the child typed. */
  matched: string;
}

interface Compiled {
  lang: TermLang;
  tier: Tier;
  re: RegExp;
}

const normaliserOf = (lang: TermLang) => (lang === "tr" ? turkishText : foldText);

const COMPILED: readonly Compiled[] = TERM_LANGS.flatMap((lang) =>
  (["age", "severe"] as const).flatMap((tier) => {
    const entries = tier === "age" ? AGE_TERMS[lang] : SEVERE_TERMS[lang];
    const re = compileEntries(entries, normaliserOf(lang));
    return re ? [{ lang, tier, re }] : [];
  }),
);

/** The first unsafe term found in `text`, in any of the seven languages, or null. `tiers` narrows what is checked (default: both). */
export function findUnsafeTerm(text: string, tiers: readonly Tier[] = ["age", "severe"]): TermHit | null {
  if (typeof text !== "string" || text.length === 0) return null;
  const folded = foldText(text);
  const looks = unleet(folded);
  const turkish = turkishText(text);
  for (const c of COMPILED) {
    if (!tiers.includes(c.tier)) continue;
    const forms = c.lang === "tr" ? [turkish] : looks === folded ? [folded] : [folded, looks];
    for (const form of forms) {
      const m = c.re.exec(form);
      if (m) return { lang: c.lang, tier: c.tier, matched: m[0] };
    }
  }
  return null;
}

export const containsUnsafeTerm = (text: string, tiers?: readonly Tier[]): boolean => findUnsafeTerm(text, tiers) !== null;

/** How many entries each list holds, for the docs and the tests. */
export const TERM_COUNTS: Record<TermLang, Record<Tier, number>> = Object.fromEntries(
  TERM_LANGS.map((l) => [l, { age: AGE_TERMS[l].length, severe: SEVERE_TERMS[l].length }]),
) as Record<TermLang, Record<Tier, number>>;
