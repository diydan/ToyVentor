#!/usr/bin/env python3
"""Export the verified catalog to the app's set-file format (the shape of the app's sets/base.json).

Writes to app_export/:
  sets/catalog.json   every verified part, as one set
  sets/base.json      the app's base set, re-pointed at catalog parts where one exists (ids kept, so saved builds and code still work)
  parts/<id>.stl      print file, already in print orientation (the app's "orientation": "flat" = print it as it loads)
  parts/<id>.glb      AR and game model: use orientation, metres, Y-up, standing on y = 0, centred on x/z
  assets.json         sidecar keyed by app id: source part, files, size, checks, print estimate (filament, time, brim), safety, gear data
  set.schema.json     the set-file contract as read off the app's base.json (strict: no unknown fields)

Set files carry only the fields the app's base.json uses, so a strict app-side validator accepts them; everything else is in assets.json.
Lattice: Snap Small 12.5 mm per stud, Snap Large 25 mm, Pro 12.5 mm holes (decided 2026-10-28). footprintMm = grid units x pitch.

Usage: python3 make_app_export.py [--app-base path/to/app/sets/base.json] [--pro-profile NAME] [--stats stat_values.json]
"""
import argparse
import json
import math
import shutil
import sys
from pathlib import Path

import numpy as np
import trimesh

import toyventor_assembly as asm
import toyventor_parts as tp

HERE = Path(__file__).parent
OUT = HERE / "app_export"
PITCH = {"small": 12.5, "large": 25.0, "pro": 12.5}
PROFILE = {"small": "stud_profile_small", "large": "stud_profile_large"}
COLOUR = {"snap": [0.24, 0.48, 0.91, 1.0], "motion": [0.45, 0.48, 0.52, 1.0], "pro": [0.95, 0.72, 0.24, 1.0]}

# The app's base parts that have a catalog counterpart. Ids stay the app's; geometry, size and checks come from the catalog.
BASE_MAP = {
    "snap-brick-2x2-small": "brick_s_2x2",
    "snap-brick-2x2-large": "big_blue_brick",
    "forge-mount-small": "forge_mount_ring_s",
    "snap-wing-01": "cloud_wings",
    "snap-glow-capsule-01": "glow_capsule",
    "pro-beam-su05": "beam_str_tu05",
    "snap-spoiler-01": "racer_spoiler",
}

# Seeded sets, each from a catalog family. A new set is one entry here (or, later, its own set file in the app with no code change).
SETS = [{"id": "forge-club-month1-racer", "name": "Forge Club Month 1: Racer", "family": "racer"},
        {"id": "forge-club-month2-critters", "name": "Forge Club Month 2: Critters",
         "parts": ["pointy_ears", "bumper_horns", "cloud_wings", "pebble_armor_shell", "waddle_tail_s", "bounce_capsule_s"]},
        {"id": "robot-bolt", "name": "Robot: Bolt", "family": "robot"}]


def app_id(part, line, reverse):
    return reverse.get(part["id"]) or f"{line}-{part['id'].replace('_', '-')}"


def units_for(part, row):
    size = part["size_class"]
    g = (row.get("build") or {}).get("grid")
    if g and size != "pro":
        return [int(g[0]), int(g[1])]
    if row.get("build", {}).get("fn") == "beam" and "length_tu" in row["build"]:
        return [int(row["build"]["length_tu"]), 1]
    p = PITCH[size]
    bx, by = part["bbox_mm"][:2]
    return [max(1, math.ceil(bx / p - 0.05)), max(1, math.ceil(by / p - 0.05))]


def mount_for(part, line):
    if part["family"] == "forge_mount":
        return "forge-mount"
    return "stud" if line == "snap" else "hole"


def glb_bytes(m, line):
    tm = tp.to_trimesh(m)
    tm.apply_scale(0.001)                                            # millimetres -> metres
    tm.apply_transform(trimesh.transformations.rotation_matrix(-math.pi / 2, [1, 0, 0]))   # z-up -> y-up
    lo, hi = tm.bounds
    shift = np.array([-(lo[0] + hi[0]) / 2, -lo[1], -(lo[2] + hi[2]) / 2])
    tm.apply_translation(shift)                                                          # stand on y = 0, centred
    tm.visual = trimesh.visual.TextureVisuals(material=trimesh.visual.material.PBRMaterial(
        baseColorFactor=COLOUR[line], metallicFactor=0.0, roughnessFactor=0.6))
    return tm.export(file_type="glb"), (tm.bounds[1] - tm.bounds[0]), shift                # shift = where the part's own origin landed


def app_pro_profile(app_base):
    return next((p["grid"]["profile"] for p in app_base["parts"] if p["line"] in ("motion", "pro")), None)


README = """# Catalog export for the app

Generated by `make_app_export.py` from the verified catalog. Do not edit by hand; re-run the exporter.

## What is here

- `sets/catalog.json`: the {n} verified parts in the sizes on offer, as one set, in the app's set-file format. Parked sizes ({parked}) are left out.
- `sets/forge-club-month1-racer.json`: the first seeded Forge Club set: six car add-ons and a wheel set (Axle Block, Racer Wheel, Racer Axle). Skins and the theme loop stay app-side.
- `scenes/pro-gear-demo.glb` and `.json`: the demo's Motion moment, validated as a build: the Pro Forge Mount, a 5-hole beam, two friction pins, two shafts and a 10- and a 20-tooth gear meshing. Each gear and its shaft are their own node, centred on its axis: rotate a node about its local Y at the `spin` speed (the big gear turns at minus half the small gear's speed). The JSON carries the gear-ratio readout.
- `sets/forge-club-month2-critters.json`: the second seeded set: Pointy Ears, Bumper Horns, Cloud Wings, Pebble Armor Shell, Waddle Tail and Bounce Capsule (head, head, back, body, tail, top), each with a different stat.
- `slots.json`: for the character and level editors: which parts fit each slot (character head, back, body, top, tail; vehicle front, rear, hood, roof, wheels). Each such part's entry in `assets.json` has `attach`: its slots, `anchorM` (the attach point, the centre of its stud holes, in the part's GLB coordinates, which matters for lopsided parts like the tail), and `frontGlb` (which way faces the toy's front, or null when symmetric).
- `sets/robot-bolt.json` and `robots/bolt.glb` (+ `.json`): Bolt, the first Snap robot. Five printed parts stack on studs (legs, torso, arms, head, back pack); the GLB has one node per part, chained as they stack, with Idle, Walk, Jump and Victory clips (rigid toy animation, no skinning). `robots/bolt.json` maps each node to its part id and lists the clips. The robot slots are in `slots.json`.
- `sets/base.json`: the app's base set, re-pointed at catalog parts where one exists. App ids are kept, so code, saved builds and the demo flow still work.
- `parts/<id>.stl`: the print file, already in print orientation. The set's `"orientation": "flat"` means print it as it loads.
- `parts/<id>.glb`: the AR and game model, in use orientation, in metres, Y-up, standing on y = 0 and centred on x and z.
- `assets.json`: everything the set files do not carry, keyed by app id:
  - the source part, file paths, the true size (`bboxMm`), the design status and the small-parts result;
  - the pre-print check: `verdict`, `summary`, `printSettings` (a brim), `filamentG`, `printTimeMin` and `filamentCostUsd` (filament only);
  - gear data where there is any.
- `set.schema.json`: the set-file contract as read off the app's `base.json`. It is strict, and the app's own file passes it.
- `stat_values.template.json`: stat values to set (see below).

## Base set mapping

| App id | Catalog part | Name now | Footprint |
| --- | --- | --- | --- |
{rows}

Removed because their size is not offered (parked: {parked}; Snap is ages 3 and up only): {removed}.

Carried over without catalog geometry: {carried}. A carried part that was printable is now `printable: false`. Its only print file is on the old grid, and a print that does not fit is worse than none.

## Changes the app needs

1. **Grid pitch.** Snap Small is 12.5 mm per stud (was 16) and Snap Large is 25 mm (was 32), so Snap and Motion share one lattice. The builder's grid snapping and stud constants must use these numbers. `footprintMm` follows the app's rule: grid units x pitch. The true size is `bboxMm` in `assets.json`, and the GLB is true size, so AR needs no scaling.
2. **Pro grid profile name.** Exported as `{pro_profile}`. The app's current name is `{base_profile}`. Rename it in the app, or re-run with `--pro-profile <name>`. This goes with the open licensing and credit decision.
3. **Stats.** The six mapped base parts keep the app's stat names and values. Every other part uses the catalog's stat name, lower case, with value 1. Set the values in `stat_values.template.json` and save it as `stat_values.json` beside the exporter. If the app accepts only a fixed list of stat names, the names need folding into that list.
4. **Print gate.** `printable` is true only when the part is verified and its pre-print verdict is not `fail`. Send `printSettings` (a brim, for some pins, shafts and capsules) with every print. `filamentG` and `printTimeMin` fill the Finish screen's estimate.

## Regenerate

`python3 make_app_export.py [--app-base app_input/base.json] [--pro-profile NAME] [--stats stat_values.json]`
"""


def export_scene(lib, items, readout, ids, path_glb, colours):
    """One GLB for the whole scene (metres, Y-up, standing on y = 0, centred). Each item is its own node; an item that spins is centred on
    its axis, so the app animates it by rotating the node about its local Y."""
    zup_to_yup = trimesh.transformations.rotation_matrix(-math.pi / 2, [1, 0, 0])
    meshes = []
    for it in items:
        tm = tp.to_trimesh(asm.placed_geometry(lib, it))
        tm.apply_scale(0.001)
        tm.apply_transform(zup_to_yup)
        meshes.append(tm)
    lo = np.min([m.bounds[0] for m in meshes], axis=0); hi = np.max([m.bounds[1] for m in meshes], axis=0)
    offset = np.array([-(lo[0] + hi[0]) / 2, -lo[1], -(lo[2] + hi[2]) / 2])
    spinning = {i for group in readout["spin"] for i in group["items"]}
    scene, nodes = trimesh.Scene(), []
    for it, tm in zip(items, meshes):
        tm.apply_translation(offset)
        pivot = np.zeros(3)
        if it["id"] in spinning:                                      # the axis: the item's pose origin, mapped like the mesh
            pivot = (zup_to_yup[:3, :3] @ (np.array([it["pose"]["x"], it["pose"]["y"], 0.0]) * 0.001)) + offset
            pivot[1] = 0.0
            tm.apply_translation(-pivot)
        tm.visual = trimesh.visual.TextureVisuals(material=trimesh.visual.material.PBRMaterial(
            baseColorFactor=colours.get(it["id"], colours.get(it["part"], [0.6, 0.6, 0.65, 1.0])), metallicFactor=0.0, roughnessFactor=0.6))
        scene.add_geometry(tm, node_name=it["id"], geom_name=it["id"], transform=trimesh.transformations.translation_matrix(pivot))
        nodes.append({"node": it["id"], "partId": ids[it["part"]], "sourceId": it["part"], "pivotM": [round(float(v), 5) for v in pivot],
                      "spins": it["id"] in spinning})
    path_glb.write_bytes(scene.export(file_type="glb"))
    return nodes, [round(float(v), 4) for v in (hi - lo)]


def set_schema():
    """The set-file contract as read off the app's base.json. Strict, so it catches a field the app would not expect."""
    grid = {"type": "object", "additionalProperties": False, "required": ["units", "profile"],
            "properties": {"units": {"type": "array", "items": {"type": "integer", "minimum": 1}, "minItems": 2, "maxItems": 2},
                           "profile": {"type": "string"}}}
    part = {"type": "object", "additionalProperties": False,
            "required": ["id", "name", "line", "mount", "sizeClass", "grid", "footprintMm", "stat", "printable"],
            "properties": {"id": {"type": "string"}, "name": {"type": "string"}, "line": {"enum": ["snap", "motion", "pro"]},
                           "mount": {"enum": ["stud", "hole", "forge-mount"]}, "sizeClass": {"enum": ["small", "large"]}, "grid": grid,
                           "footprintMm": {"type": "array", "items": {"type": "number"}, "minItems": 2, "maxItems": 2},
                           "stat": {"type": "object", "additionalProperties": False, "required": ["name", "value"],
                                    "properties": {"name": {"type": "string"}, "value": {"type": "integer", "minimum": 1}}},
                           "printable": {"type": "boolean"}, "orientation": {"enum": ["flat"]}, "supportFree": {"type": "boolean"},
                           "skin": {"type": "string"}}}
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "title": "ToyVentor set file (as read off the app's sets/base.json)",
            "type": "object", "additionalProperties": False, "required": ["id", "name", "parts"],
            "properties": {"id": {"type": "string"}, "name": {"type": "string"}, "parts": {"type": "array", "items": part}}}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--app-base", default=str(HERE / "app_input" / "base.json"), help="the app's current sets/base.json (input copy)")
    ap.add_argument("--pro-profile", default="hole_grid_12.5", help="grid profile name the app uses for Pro holes")
    ap.add_argument("--stats", default=str(HERE / "stat_values.json"), help="optional {part id: value} overrides for stat values")
    a = ap.parse_args(argv)

    man = {p["id"]: p for p in json.loads((HERE / "toyventor_parts.json").read_text())["parts"] if p.get("file")}
    rows = {r["id"]: r for r in json.loads((HERE / "catalog.json").read_text())["parts"]}
    reports = {}
    for f in (HERE / "validation").glob("*.json"):
        if f.name != "summary.json":
            r = json.loads(f.read_text())
            reports[r["part_id"]] = r
    app_base = json.loads(Path(a.app_base).read_text())
    base_by_id = {p["id"]: p for p in app_base["parts"]}
    reverse = {v: k for k, v in BASE_MAP.items()}
    stat_values = json.loads(Path(a.stats).read_text()) if Path(a.stats).exists() else {}
    lib = asm.Library(str(HERE / "toyventor_parts.json"))
    parked = set((json.loads((HERE / "interfaces.json").read_text()).get("product", {}).get("parked") or {}).keys())   # sizes not offered

    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "sets").mkdir(parents=True)
    (OUT / "parts").mkdir()

    entries, assets = {}, {}
    for pid, part in man.items():
        if part["size_class"] in parked:
            continue                                                  # a parked size is not exported
        row = rows[pid]
        line = row["line"]                                            # the catalog's line (Forge Mounts are 'shared' in the manifest)
        aid = app_id(part, line, reverse)
        size = part["size_class"]
        units = units_for(part, row)
        rep = reports.get(pid, {})
        printable = part["design_status"] == "verified" and rep.get("verdict") not in (None, "fail")
        support_free = all(c["result"] == "pass" for c in part["checks"] if c["id"] == "P1_no_supports")
        old = base_by_id.get(aid)
        stat = dict(old["stat"]) if old else {"name": part["stat"].lower(), "value": int(stat_values.get(aid, stat_values.get(pid, 1)))}
        entries[aid] = {"id": aid, "name": part["name"], "line": line, "mount": mount_for(part, line),
                        "sizeClass": "large" if size == "large" else "small",
                        "grid": {"units": units, "profile": PROFILE.get(size, a.pro_profile)},
                        "footprintMm": [round(units[0] * PITCH[size], 2), round(units[1] * PITCH[size], 2)],
                        "stat": stat, "printable": printable, "orientation": "flat", "supportFree": support_free}
        shutil.copyfile(HERE / part["file"], OUT / "parts" / f"{aid}.stl")
        glb, ext, anchor = glb_bytes(lib.geometry(pid), line)
        (OUT / "parts" / f"{aid}.glb").write_bytes(glb)
        s = rep.get("slicer") or {}
        assets[aid] = {
            "sourceId": pid, "type": part.get("type"), "behavior": part.get("behavior"),
            "stl": f"parts/{aid}.stl", "glb": f"parts/{aid}.glb",
            "bboxMm": part["bbox_mm"], "glbSizeM": [round(float(v), 4) for v in ext], "volumeCm3": part.get("volume_cm3"),
            "designStatus": part["design_status"],
            "preprint": {"verdict": rep.get("verdict"), "summary": rep.get("summary"), "printSettings": rep.get("print_settings", {}),
                         "filamentG": s.get("filament_g"), "printTimeMin": round(s["print_time_s"] / 60, 1) if s.get("print_time_s") else None,
                         "filamentCostUsd": s.get("filament_cost_usd"), "slicer": s.get("engine")},
            "safety": {"smallPart": part["safety"]["small_part_status"]},
            "statSource": "app base set" if old else ("stat_values.json" if (aid in stat_values or pid in stat_values) else "catalog name, default value 1 (proposal)"),
        }
        if part.get("gear"):
            assets[aid]["gear"] = part["gear"]
        if row.get("attach"):                                         # where it goes on a toy, for the editors
            at = row["attach"]
            assets[aid]["attach"] = {"kind": at["kind"], "slots": at["slots"], "symmetric": at["front"] == "symmetric",
                                     "frontGlb": None if at["front"] == "symmetric" else ([0, 0, 1] if at["front"] == "-y" else [0, 0, -1]),
                                     "anchorM": [round(float(v), 5) for v in anchor]}

    catalog_set = {"id": "catalog", "name": "ToyVentor Catalog", "parts": sorted(entries.values(), key=lambda e: (e["line"], e["id"]))}
    base_parts, carried, removed = [], [], []
    for old in app_base["parts"]:
        if old["sizeClass"] in parked or (old["id"] in BASE_MAP and man.get(BASE_MAP[old["id"]], {}).get("size_class") in parked):
            removed.append(old["id"])                                 # the size this part belongs to is not offered
            continue
        if old["id"] in entries:
            e = dict(entries[old["id"]])
            if old.get("skin"):
                e["skin"] = old["skin"]
            base_parts.append(e)
        else:                                                         # no catalog geometry: carried over, footprint moved to the new lattice
            e = dict(old)
            size = "large" if old["sizeClass"] == "large" else ("pro" if old["line"] in ("motion", "pro") else "small")
            e["footprintMm"] = [round(u * PITCH[size], 2) for u in old["grid"]["units"]]
            if old["line"] in ("motion", "pro"):
                e["grid"] = dict(old["grid"], profile=a.pro_profile)
            if e.get("printable"):
                e["printable"] = False                                # its only print file is on the old grid: no Print until it exists on this one
            base_parts.append(e)
            carried.append(old["id"])
            assets[old["id"]] = {"sourceId": None, "note": ("no catalog geometry on the 12.5/25 mm lattice yet; the app's own print file is on the old grid"
                                                            if old.get("printable") else "skin only: game and AR, nothing to print")}
    base_set = {"id": app_base["id"], "name": app_base["name"], "parts": base_parts}

    (OUT / "sets" / "catalog.json").write_text(json.dumps(catalog_set, indent=2, ensure_ascii=False) + "\n")
    (OUT / "scenes").mkdir()
    items, readout = asm.motion_gear_scene(lib)
    check = asm.validate(lib, items)
    ids = {it["part"]: next(aid for aid, a in assets.items() if a.get("sourceId") == it["part"]) for it in items}
    colours = {"mount": [0.45, 0.48, 0.52, 1.0], "beam": [0.24, 0.48, 0.91, 1.0], "gearA": [0.95, 0.55, 0.15, 1.0], "gearB": [0.2, 0.68, 0.6, 1.0],
               "shaft_tu03": [0.92, 0.75, 0.3, 1.0], "pin_friction": [0.92, 0.75, 0.3, 1.0]}
    nodes, size_m = export_scene(lib, items, readout, ids, OUT / "scenes" / "pro-gear-demo.glb", colours)
    (OUT / "scenes" / "pro-gear-demo.json").write_text(json.dumps({
        "id": "pro-gear-demo", "name": "Motion gear set on the Forge Mount", "glb": "scenes/pro-gear-demo.glb", "sizeM": size_m,
        "validated": {"ok": check["ok"], "joints": len(check["edges"]), "errors": check["errors"]},
        "nodes": nodes,
        "readout": {"driver": dict(readout["driver"], partId=ids["gear_spur_z10"]), "driven": dict(readout["driven"], partId=ids["gear_spur_z20"]),
                    "ratio": readout["ratio"], "ratioText": readout["ratio_text"], "explain": readout["explain"],
                    "moduleMm": readout["module_mm"], "centreDistanceMm": readout["centre_distance_mm"]},
        "spin": [{"nodes": g["items"], "speed": g["speed"], "axis": "local +y"} for g in readout["spin"]],
    }, indent=2) + "\n")
    slots = {}
    for aid, asset in sorted(assets.items()):
        if asset.get("attach"):
            for sl in asset["attach"]["slots"]:
                slots.setdefault(asset["attach"]["kind"], {}).setdefault(sl, []).append(aid)
    (OUT / "slots.json").write_text(json.dumps({
        "conventions": {"anchorM": "GLB coordinates of the part's attach point: the centre of its stud holes (or hole grid) on its underside. Place this point on the toy's mount; the part's up is +y.",
                        "frontGlb": "The direction, in the part's GLB, that faces the toy's front (+z for most parts). null when the part is symmetric and can face either way.",
                        "kinds": {"character": ["head", "back", "body", "top", "tail"], "vehicle": ["front", "rear", "hood", "roof", "wheels"],
                                  "robot": ["legs", "torso", "arms", "head", "back"]}},
        "slots": slots}, indent=2) + "\n")
    import make_robot_glb as _mr                                    # animated robots: one node per printed part, rigid toy animation
    robot_meta = [_mr.export_robot(lib, key, OUT / "robots", {a["sourceId"]: aid for aid, a in assets.items() if a.get("sourceId")}) for key in _mr.ROBOTS]
    seeded = []
    for st in SETS:
        members = sorted((e for aid, e in entries.items() if (assets[aid]["sourceId"] in st["parts"] if "parts" in st
                          else rows[assets[aid]["sourceId"]]["family"] == st["family"])), key=lambda e: e["id"])
        if members:
            (OUT / "sets" / f"{st['id']}.json").write_text(json.dumps({"id": st["id"], "name": st["name"], "parts": members}, indent=2, ensure_ascii=False) + "\n")
            seeded.append(f"{st['id']} ({len(members)} parts)")
    (OUT / "sets" / "base.json").write_text(json.dumps(base_set, indent=2, ensure_ascii=False) + "\n")
    (OUT / "assets.json").write_text(json.dumps({"lattice_mm": PITCH, "units": "STL in mm (print orientation); GLB in metres, y-up, use orientation",
                                                 "parts": assets}, indent=2, ensure_ascii=False) + "\n")
    (OUT / "set.schema.json").write_text(json.dumps(set_schema(), indent=2) + "\n")
    template = {e["id"]: {"stat": e["stat"]["name"], "value": e["stat"]["value"]} for e in catalog_set["parts"]
                if assets[e["id"]]["statSource"].startswith("catalog")}
    (OUT / "stat_values.template.json").write_text(json.dumps({"_how": "Set each value, keep only the number per id, and save as stat_values.json beside make_app_export.py, e.g. {\"pro-gear-spur-z20\": 2}. Stat names are the catalog's proposals.",
                                                             "parts": template}, indent=2) + "\n")
    rows_md = "\n".join(f"| `{aid}` | `{src}` | {entries[aid]['name']} | {entries[aid]['footprintMm'][0]:g} x {entries[aid]['footprintMm'][1]:g} mm |"
                         for aid, src in BASE_MAP.items() if aid in entries)
    (OUT / "README.md").write_text(README.format(n=len(catalog_set["parts"]), rows=rows_md, carried=", ".join(f"`{c}`" for c in carried) or "none",
                                                 removed=", ".join(f"`{r}`" for r in removed) or "none", parked=", ".join(sorted(parked)) or "none",
                                                 pro_profile=a.pro_profile, base_profile=app_pro_profile(app_base) or "unchanged"))
    print(f"catalog set: {len(catalog_set['parts'])} parts | base set: {len(base_parts)} parts "
          f"({len(base_parts) - len(carried)} on catalog geometry, carried over: {', '.join(carried)}; removed (parked size): {', '.join(removed) or 'none'}) | seeded: {', '.join(seeded)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
