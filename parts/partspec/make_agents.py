"""Generate AGENTS.md from interfaces.json + the part manifest.

The instructions an AI agent follows are derived from the same model it edits, so they
cannot drift. Run after every regeneration:  python3 make_agents.py out
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
IF = json.loads((HERE / "interfaces.json").read_text())

ERROR_FIXES = [
    ("unknown_part", "The part id is not in the catalog. Pick an id from the catalog table."),
    ("duplicate_id", "Every placement needs a unique id."),
    ("size_mismatch", "The two connectors have different size classes. Choose a child part whose connector has the same size class as the parent's."),
    ("misaligned", "The parts touch on the same plane but no studs line up. Use attach() with explicit parent and child cells instead of raw coordinates."),
    ("floating", "A part is not connected to the first placement. Attach it to something with attach()."),
    ("profile_mismatch", "A pin and a bore that `pin_bore.rules` does not allow together (a round pin in a fixed bore, for example). Use a pin profile the bore class accepts, or a different bore."),
    ("gear_mesh_distance", "Two gears (or a gear and a rack or ring) reach each other but are not at their meshing distance: m (z1 + z2) / 2, m (z_ring - z) / 2, or the pitch radius from a rack. Move one by a bore or pick a tooth count that fits."),
    ("unsupported_pose", "A stud or socket part was tipped over. Stud parts stay upright; only Pro parts tip."),
    ("collision", "Two parts occupy the same space. Move one to a different parent cell, rotate it, or choose a smaller part."),
]


def build(out):
    out = Path(out)
    man = json.loads((out / "toyventor_parts.json").read_text())
    idx = json.loads((out / "toyventor_index.json").read_text())
    try:
        sys.path.insert(0, str(HERE))
        from toyventor_assembly import ENFORCED_MATES
    except Exception:
        ENFORCED_MATES = [("stud_grid", "socket_grid")]
    parts = [p for p in man["parts"] if p.get("file")]
    lat = IF["lattice"]
    L = []
    w = L.append

    w(f"# ToyVentor: agent instructions\n")
    w(f"> Generated by `make_agents.py` from `interfaces.json` v{IF['version']} and `toyventor_parts.json`. Do not edit by hand: change the source, then regenerate.\n")
    w("## What this is\n")
    w("ToyVentor parts (Snap for kids, Pro for makers) are generated by code, described by a manifest with typed connectors, and assembled into designs. "
      "This file tells you how to change the model and how to build designs from it without breaking compatibility.\n")
    w(f"Status: {IF['status']}\n")

    w("## Rules\n")
    rules = [
        "`interfaces.json` is the single source of truth for numbers, limits, check severities, safety constants and print-page warnings. Never hard-code a value that exists there.",
        "Change the source first (`interfaces.json` or the part code), then regenerate. Generated files are never the source: the STLs, `toyventor_parts.json`, `toyventor_index.json`, `INTERFACE_STANDARD.md` and this file.",
        "Never invent connector kinds, interface ids, check ids or part ids. The schema and the catalog below define what exists. If something you need is missing, report the gap instead of working around it.",
        "Prefer existing parts to new ones, and keep each change small.",
        "Before changing an interface number, run the impact query and recheck every part it lists.",
        "Never report a physical check (`F1_printed_fit`, `F2_breakage`) as passed. They stay pending until a real print.",
        "Use only parts whose `design_status` is `verified` in designs, unless the user says otherwise. The generator computes `design_status` from the checks; never set it by hand.",
        "Do not name third-party construction systems or their trademarks in part names, specs, UI text or comments.",
        "Do not describe any part as safe for children under 3. That needs a lab test and is outside what this model can show.",
    ]
    for i, r in enumerate(rules, 1):
        w(f"{i}. {r}")
    w("")

    w("## Commands\n")
    w("| Task | Command |\n| --- | --- |")
    for k, v in IF["tooling"]["commands"].items():
        w(f"| {k.replace('_', ' ')} | `{v}` |")
    w("")

    w("## Workflow\n")
    w("```text\ntask -> impact query (index) -> smallest edit to interfaces.json or part code -> generate -> read failing checks\n"
      "     -> build_check (assembly demos) -> regenerate standard + agents -> selftest\n```\n")
    w("Leave the model valid: `generate` must report no blocking failures and `selftest` must pass before you finish.\n")
    w("Before a new or changed part ships, run `python3 preprint_check.py --catalog --part <id>` (see `PREPRINT_VALIDATION.md`). Its report must not be `fail`, and any `print_settings` it gives (a brim) travel with the file.\n")

    cf = IF["conformance"]
    w("## Creating or changing a part\n")
    w(f"A part conforms when its status is `verified`. {cf['status_rule']['verified']} Otherwise it is `needs_reproportion`. {cf['status_note']}\n")
    for i, step in enumerate(cf["authoring_steps"], 1):
        w(f"{i}. {step}")
    w("\nRules every part follows:\n")
    for r_ in cf["authoring_rules"]:
        w(f"- {r_}")
    w("")
    w("## Lattice and interfaces\n")
    w(f"One base unit: 1 {lat['unit_name']} = {lat['unit_mm']} mm. {lat['rule']} {lat.get('nesting', '')}\n")
    w("| Interface | Kind | Size class | Pitch (mm) | Fit class | Clearance (mm) |\n| --- | --- | --- | --- | --- | --- |")
    for name, i in IF["interfaces"].items():
        pitch = i.get("pitch", i.get("pitch_tu", 1) * lat["unit_mm"])
        w(f"| `{name}` | {i['kind']} | {i['size_class']} | {pitch} | {i['fit_class']} | {i.get('fit', 'n/a')} |")
    w(f"\n{IF['fit_note']}\n")

    w("## Part catalog\n")
    w("| Part id | Line | Size | Status | Stat | Connectors |\n| --- | --- | --- | --- | --- | --- |")
    for p in parts:
        cs = "; ".join(f"`{c['id']}` {c['kind']}/{c['gender']}" + (f" {c['grid']['nx']}x{c['grid']['ny']}" if "grid" in c else "") for c in p["connectors"])
        w(f"| `{p['id']}` | {p['line']} | {p['size_class']} | {p.get('design_status', '?')} | {p['stat']} | {cs} |")
    w("")

    w("## Building a design\n")
    w("Never write coordinates. Pick parts and connectors; the library computes the pose so alignment is correct by construction.\n")
    w("```python\nfrom toyventor_assembly import Library, place, attach, validate\n"
      "lib = Library('out/toyventor_parts.json')\n"
      "ring  = place('forge_mount_ring', pid='ring')\n"
      "brick = attach(lib, ring, 'top_studs', 'big_blue_brick', 'under_sockets', parent_cell=(0, 0), child_cell=(0, 0), pid='brick')\n"
      "result = validate(lib, [ring, brick])   # {'ok', 'errors', 'warnings', 'edges'}\n```\n")
    enforced = ", ".join(f"{a} with {b}" for a, b in ENFORCED_MATES)
    w(f"The validator enforces: {enforced}. Pin-and-bore pairs must be listed in `pin_bore.rules`. Pose is limited to turns about z, so pins run along z; perpendicular pins (cross holes) arrive with the T beam in W4.\n")
    w("When `validate` rejects a build, read the code and fix it:\n")
    w("| Code | What to do |\n| --- | --- |")
    for code, fix in ERROR_FIXES:
        w(f"| `{code}` | {fix} |")
    w("\nWarning `unverified_part` means a part is not re-proportioned to the current lattice. Treat that design's geometry results as unreliable.\n")

    tol = IF["tolerance"]
    fit_parts = [p for p in parts if p.get("fit", {}).get("surface_offset_window_mm")]
    w("## Fit and tolerance\n")
    w("After each part is built, the generator seats it on its matching reference part, slices both at mid-stud height and measures the radial gap of every engaged stud. "
      f"`T1_fit_as_designed` (block) requires the measured gap to equal the design gap and to sit inside the limits (max play {tol['max_play_mm']} mm, max interference {tol['max_interference_mm']} mm). "
      f"`T2_fit_tolerance_window` (warn) requires it to stay inside those limits when printers are calibrated to +/-{tol['surface_error_calibrated_mm']} mm per surface. "
      "`build_check` also fit-measures every mating pair in the catalog (`fit_matrix.json`) and every connection in a build.\n")
    if fit_parts:
        lo = max(p["fit"]["surface_offset_window_mm"][0] for p in fit_parts)
        hi = min(p["fit"]["surface_offset_window_mm"][1] for p in fit_parts)
        unc = tol["surface_error_uncalibrated_mm"]
        inside = lo <= -unc and unc <= hi
        w(f"**Calibration target:** every part fits when the printer's surface offset is inside {lo:+.3f} to {hi:+.3f} mm (the intersection of all part windows). "
          f"An uncalibrated printer (+/-{unc} mm) is {'inside' if inside else 'outside'} that window, so {'calibration is optional' if inside else 'calibration is required'}.\n")
        w("| Part | Studs measured | Gap min to max (mm) | Design gap (mm) | Window (mm per surface) |\n| --- | --- | --- | --- | --- |")
        for p in fit_parts:
            f = p["fit"]
            w(f"| `{p['id']}` | {f['studs_measured']} | {f['gap_min_mm']:+.3f} to {f['gap_max_mm']:+.3f} | {f['design_gap_mm']:.3f} | {f['surface_offset_window_mm'][0]:+.3f} to {f['surface_offset_window_mm'][1]:+.3f} |")
        w("")
    w("Rules: do not change a stud, tube or `fit` number without re-running `generate` and `build_check`; a fit change moves every window. "
      "A fit that passes here is a design-time result. Never report it as a printed fit; `F1_printed_fit` stays pending until a calibration print lands inside the window.\n")
    w("## Checks and severities\n")
    w("Severity is data in `interfaces.json`. A failing `block` check stops export; `warn` is shown to the user; `info` is noted. `pending` is never a pass.\n")
    w("| Check | Group | Level | Meaning |\n| --- | --- | --- | --- |")
    for cid, c in IF["checks"].items():
        w(f"| `{cid}` | {c['group']} | {c['level']} | {c['description']} |")
    w("")

    sc = IF["safety"]["small_parts_cylinder"]
    w("## Safety\n")
    w(f"Every part is screened against the small-parts cylinder ({sc['diameter_mm']} mm across, {sc['depth_min_mm']} to {sc['depth_max_mm']} mm deep). "
      "The screen is conservative and is not a lab test. The print page shows the general notice plus the text for the part's status:\n")
    for k, v in IF["print_page_warnings"].items():
        w(f"- **{k}:** {v}")
    w("\nSmall parts are for ages 3 and up. A warning label is enough only for parts sold to ages 3 and up.\n")

    w("## Impact queries\n")
    w("Run these before changing an interface number:\n")
    w("```bash\npython3 toyventor_index.py out list\npython3 toyventor_index.py out used-by stud_large\npython3 toyventor_index.py out impact stud_large\npython3 toyventor_index.py out checks S1_small_part_screen\n```\n")
    w("| Interface | Parts using it | Mating pairs |\n| --- | --- | --- |")
    for iface, e in sorted(idx["interfaces"].items()):
        w(f"| `{iface}` | {', '.join(f'`{p}`' for p in sorted(e['uses']))} | {len(e['mates'])} |")
    w("")

    import make_catalog
    cat = make_catalog.CAT
    pr = make_catalog.progress(cat, man)
    w("## Catalog (end game)\n")
    w(f"{cat['goal']} The plan is `catalog.json`; progress is `CATALOG.md`. Add a part by adding a catalog row first, then building it with the authoring steps above.\n")
    w("| Line | Verified | Built, not verified | Target |\n| --- | --- | --- | --- |")
    for ln, s in pr["lines"].items():
        w(f"| {ln.title()} | {s['verified']} | {s['built']} | {s['target']} |")
    nxt = [x for x in pr["waves"] if x["state"] == "ready"]
    w("\nReady to build now: " + (", ".join(f"{x['id']} ({x['name']})" for x in nxt) or "none") + ".\n")
    w("Catalog rules: " + " ".join(cat["rules"]) + "\n")
    w("## Open items\n")
    todo = [p["id"] for p in parts if p.get("design_status") != "verified"]
    w(f"- Parts still to be re-proportioned to the current lattice: {', '.join(f'`{t}`' for t in todo) or 'none'}.")
    w("- Parts in a build can tip onto their side in quarter turns (`place(..., tilt=(rx, ry))`, or `place_on_axis` to seat a pin, shaft or hub on any axis). Stud parts always stay upright.")
    planned = [f"`{k}`" for k in IF["planned_checks"] if not k.startswith("_")]
    if planned:
        w(f"- Planned checks, not yet enforced: {', '.join(planned)}. Each moves into `checks` in the same change that adds the code that emits it.")
    dormant = sorted(set(IF["checks"]) - {c["id"] for p in man["parts"] for c in p["checks"]})
    if dormant:
        w(f"- Dormant checks (they apply to no part yet, and the selftest proves them on fixtures): {', '.join(f'`{d}`' for d in dormant)}.")
    w("- Interface numbers are targets. Nothing has been printed. Clearance values are placeholders until the calibration piece has been through fit loops.")
    w("- Physical checks `F1_printed_fit` and `F2_breakage` are pending for every part.\n")

    (Path(out) / "AGENTS.md").write_text("\n".join(L))
    return len(L)


if __name__ == "__main__":
    n = build(sys.argv[1] if len(sys.argv) > 1 else "out")
    print(f"AGENTS.md written ({n} lines)")
