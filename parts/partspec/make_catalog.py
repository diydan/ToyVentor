"""Catalog board: progress toward the top 30 Snap parts and the top 30 Pro parts.

catalog.json is the plan (what we are building, in which wave). The manifest is the truth about what exists:
a part counts as verified only when the generator says so. Writes CATALOG.md.   python3 make_catalog.py out
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
CAT = json.loads((HERE / "catalog.json").read_text())


def progress(catalog, manifest):
    status = {p["id"]: p.get("design_status", "needs_reproportion") for p in manifest["parts"] if p.get("file")}
    parts = []
    for p in catalog["parts"]:
        st = "planned" if p["id"] not in status else ("verified" if status[p["id"]] == "verified" else "built")
        parts.append({**p, "status": st})
    waves, done = [], {}
    for w in catalog["waves"]:
        mine = [p for p in parts if p["wave"] == w["id"]]
        done[w["id"]] = all(p["status"] == "verified" for p in mine) if mine else bool(w.get("done"))
    for w in catalog["waves"]:
        mine = [p for p in parts if p["wave"] == w["id"]]
        state = "done" if done[w["id"]] else ("ready" if all(done[r] for r in w["requires"]) else "blocked")
        waves.append({**w, "parts": len(mine), "verified": sum(p["status"] == "verified" for p in mine), "state": state})
    lines = {ln: {"target": t, "verified": sum(p["status"] == "verified" for p in parts if p["line"] == ln),
                  "built": sum(p["status"] == "built" for p in parts if p["line"] == ln)} for ln, t in catalog["targets"].items()}
    return {"parts": parts, "waves": waves, "lines": lines, "next": [w["id"] for w in waves if w["state"] == "ready"]}


def build(out):
    out = Path(out)
    pr = progress(CAT, json.loads((out / "toyventor_parts.json").read_text()))
    L = []
    w = L.append
    w("# ToyVentor catalog: top 30 Snap and top 30 Pro\n")
    w("> Generated by `make_catalog.py` from `catalog.json` and `toyventor_parts.json`. Edit the catalog, not this file. A part counts as verified only when the generator marks it verified.\n")
    w(f"**Goal:** {CAT['goal']}\n")
    w("| Line | Verified | Built, not verified | Target |\n| --- | --- | --- | --- |")
    for ln, s in pr["lines"].items():
        w(f"| {ln.title()} | {s['verified']} | {s['built']} | {s['target']} |")
    w("\n## Waves\n")
    w("| Wave | What | Parts | Verified | Needs | Effort | State |\n| --- | --- | --- | --- | --- | --- | --- |")
    for x in pr["waves"]:
        w(f"| {x['id']} | {x['name']} | {x['parts'] or 'n/a'} | {x['verified'] if x['parts'] else 'n/a'} | {', '.join(x['requires']) or 'none'} | {x['effort']} | {x['state']} |")
    w("")
    for x in pr["waves"]:
        w(f"- **{x['id']}:** {x['scope']}")
    w("\n## How parts were picked\n")
    for c in CAT["criteria"]:
        w(f"- {c}")
    w("\n**Rules:**\n")
    for r in CAT["rules"]:
        w(f"- {r}")
    for ln in CAT["targets"]:
        w(f"\n## {ln.title()} parts\n")
        w("| Id | Name | Family | Size | Wave | Status | Notes |\n| --- | --- | --- | --- | --- | --- | --- |")
        for p in sorted((p for p in pr["parts"] if p["line"] == ln), key=lambda p: (p["wave"] or "", p["id"])):
            w(f"| `{p['id']}` | {p['name']} | {p['family']} | {p['size']} | {p['wave'] or 'built'} | {p['status']} | {(p.get('stat') + '. ' if p.get('stat') else '') + p['note']} |")
    (out / "CATALOG.md").write_text("\n".join(L) + "\n")
    return pr


if __name__ == "__main__":
    pr = build(sys.argv[1] if len(sys.argv) > 1 else "out")
    print(" | ".join(f"{ln}: {s['verified']}/{s['target']} verified" for ln, s in pr["lines"].items()), "| ready:", ", ".join(pr["next"]) or "none")
