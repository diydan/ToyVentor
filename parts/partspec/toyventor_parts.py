def add_studs_at(m, size, nx, ny, cx, cy, z, cid="top_studs"):
    """Place an nx x ny stud grid centred at (cx, cy, z) and return (manifold, connector)."""
    p = STUD[size]
    pitch = p["pitch"]
    ox = cx - (nx - 1) / 2 * pitch
    oy = cy - (ny - 1) / 2 * pitch
    st = stud(p)
    for i in range(nx):
        for j in range(ny):
            m = m + st.translate((ox + i * pitch, oy + j * pitch, z))
    if abs(cx) < 1e-6 and abs(cy) < 1e-6 and cid == "top_studs":
        return m, stud_conn(size, nx, ny, z, cid=cid)
    conn = {
        "id": cid,
        "kind": "stud_grid",
        "gender": "M",
        "interface": f"stud_{size}",
        "size_class": size,
        "fit_class": p["fit_class"],
        "frame": {"origin": [round(ox, 4), round(oy, 4), round(z, 4)], "normal": [0, 0, 1]},
        "grid": {"nx": nx, "ny": ny, "pitch": pitch, "anchor": "corner"},
    }
    return m, conn


