def _xprism(pts, x0, x1):
    """Extrude a profile drawn in (y, z) along x, from x0 to x1."""
    a = sum(p[0] * q[1] - q[0] * p[1] for p, q in zip(pts, pts[1:] + pts[:1]))
    cs = CrossSection([pts if a > 0 else pts[::-1]])
    m = Manifold.extrude(cs, x1 - x0)
    return m.transform([[0, 0, 1, x0], [1, 0, 0, 0], [0, 1, 0, 0]])     # local (x, y, z) -> world (y, z, x)


def _half(size, n):
    p = STUD[size]
    return n * p["pitch"] / 2 - p["gap"]


def racer_spoiler(size="small", grid=(2, 1), scale=1.0, base="integrated", pad=None, lock=False):
    """Rear wing between two end plates, with a centre pylon: the wing's underside bridges about 8 mm on each side of it."""
    p, fh, foot = _foot(size, grid, base, pad)
    s = _s(size, scale)
    hx, t, d = _half(size, grid[0]), 3.0 * s, 5.0 * s
    plate = [(-d, fh - 0.5), (d, fh - 0.5), (d, fh + 9.0 * s), (-d, fh + 7.0 * s)]
    ends = _xprism(plate, hx - t, hx) + _xprism(plate, -hx, -hx + t)
    wing = _xprism([(-4.5 * s, fh + 5.0 * s), (4.5 * s, fh + 5.0 * s), (4.5 * s, fh + 7.6 * s), (-4.5 * s, fh + 6.4 * s)], -hx + t - 0.5, hx - t + 0.5)
    pylon = _xprism([(-4.5 * s, fh - 0.5), (4.5 * s, fh - 0.5), (4.5 * s, fh + 5.5 * s), (-4.5 * s, fh + 5.5 * s)], -1.2 * s, 1.2 * s)   # full wing depth: halves every bridge
    plate_low = [(-d, 0.0), (d, 0.0), (d, fh + 9.0 * s), (-d, fh + 7.0 * s)]      # end plates stand on the bed: wider than the pad, they would hang over air
    ends = _xprism(plate_low, hx - t, hx) + _xprism(plate_low, -hx, -hx + t)
    return integrated_sockets(foot + ends + keep_above(wing + pylon, fh - 0.5), size, lock)


def racer_bull_bar(size="small", grid=(2, 1), scale=1.0, base="integrated", pad=None, lock=False):
    """Front guard: two posts, a grille and three bars. Bars have a diamond section (no flat undersides), so nothing bridges."""
    from toyventor_geom import rbox
    p, fh, foot = _foot(size, grid, base, pad)
    s = _s(size, scale)
    hx, yb, H = _half(size, grid[0]), -2.0 * s, 10.5 * s
    px = hx - 1.6 * s
    body = None
    for x in (-px, px, -3.6 * s, 3.6 * s):
        w = 2.6 * s if abs(x) > 5 else 2.0 * s
        post = rbox(w, w, H + 0.5, 0.6 * s, 0.0).translate((x, yb, fh - 0.5))
        body = post if body is None else body + post
    diamond = [(-1.1 * s, 0.0), (0.0, -1.5 * s), (1.1 * s, 0.0), (0.0, 1.3 * s)]
    for zc in (fh + 3.5 * s, fh + 7.0 * s, fh + H - 1.3 * s):
        body = body + _xprism([(yb + u, zc + v) for u, v in diamond], -px, px)
    return _finish(size, grid, foot, lock, body, fh, base)


def racer_hood_scoop(size="small", grid=(2, 2), scale=1.0, base="integrated", pad=None, lock=False):
    """Low wedge with an air intake. Sides lean in as they rise; the intake roof is a 10 mm bridge."""
    p, fh, foot = _foot(size, grid, base, pad)
    s = _s(size, scale)
    hx, hy = _half(size, grid[0]) - 1.2, _half(size, grid[1]) - 1.2
    bottom = Manifold.extrude(CrossSection.square((2 * hx, 2 * hy), center=True), 0.5).translate((0, 0, fh - 0.5))
    top = Manifold.extrude(CrossSection.square((14.0 * s, 13.0 * s), center=True), 0.01).translate((0, 2.5 * s, fh + 5.0 * s))
    shell = Manifold.batch_hull([bottom, top])
    if foot is not None:
        shell = flare_clip(shell, foot.slice(fh - 0.5), fh - 0.5)          # the pad's corners are round: never overhang them
    intake = Manifold.cube((10.0 * s, 14.0 * s, 2.5 * s)).translate((-5.0 * s, -hy - 1.0, fh + 1.0 * s))
    return _finish(size, grid, foot, lock, shell - intake, fh, base)


