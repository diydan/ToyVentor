def size_tag(size):
    return {"large": "L", "small": "S", "pro": "P"}[size]


def evaluate(part, validator):
    """Run one part through the whole gate. Real parts and test fixtures take exactly the same path.
    Returns (manifest entry, mesh, blocking failures, small-parts result)."""
    m, conns, extras = part["fn"]()
    extras = dict(extras)
    rot = extras.pop("print_rotation_deg", None)
    mp = m
    if rot:                                   # printed orientation differs from the assembly frame: turn, then sit it on the bed
        mp = m.rotate(tuple(rot))
        mp = mp.translate((0, 0, -mp.bounding_box()[2]))
    tm = to_trimesh(mp)
    small = small_part_status(tm)
    fit = fit_for(part, m, conns)
    checks = run_checks(part, m, tm, conns, small, fit, extras, mp=mp)
    entry = {
        "id": part["id"], "name": part["name"], "type": part["type"], "line": part["line"], "family": part["family"], "size_class": part["size"],
        "stat": part["stat"], "behavior": part["behavior"], "prints": True, "tags": part["tags"],
        "file": f"toyventor_{part['id']}_{size_tag(part['size'])}.stl",
        "bbox_mm": (tm.bounds[1] - tm.bounds[0]).round(1).tolist(), "volume_cm3": round(tm.volume / 1000, 2),
        "connectors": conns,
        "safety": {"small_part_status": small["status"], "min_enclosing_diameter_mm": small["min_enclosing_diameter_mm"],
                   "margin_pct": small["margin_pct"], "print_page_warning": warnings_for(small["status"])},
        "print": {"orientation": ("bed = z0; lying on a flat, axis horizontal" if rot else "bed = z0; lying flat, bores and pins along z" if part["size"] == "pro" else "bed = z0; studs/body up; underside cavity down" if part["cavity"] else "bed = z0; flat, studs up"),
                  "supports": False, **({"rotation_deg": rot} if rot else {})},
        "design_status": "needs_reproportion",  # placeholder; derived below once every check has run
        "fit": fit_block(fit, part["size"]),
        "checks": checks,
    }
    entry.update(extras)
    errs = [e.message for e in validator.iter_errors(entry)]
    entry["checks"].append({"id": "M1_manifest_schema", "level": level_of("M1_manifest_schema"), "result": "pass" if not errs else "fail", "detail": "; ".join(errs[:2])})
    blocking_fail = blocking_failures(entry["checks"])
    entry["design_status"] = derive_status(entry["checks"], small, part["size"])
    return entry, tm, blocking_fail, small


def main(out="out"):
    out = Path(out)
    out.mkdir(exist_ok=True)
    validator = Draft202012Validator(SCHEMA)
    manifest = {"standard": IF["standard"], "version": IF["version"], "status": IF["status"], "units": "mm", "parts": []}
    all_ok = True
    for part in PARTS:
        entry, tm, blocking_fail, small = evaluate(part, validator)
        all_ok &= not blocking_fail
        tm.export(out / entry["file"])
        manifest["parts"].append(entry)
        warns = [c["id"] for c in entry["checks"] if c["result"] == "fail" and level_of(c["id"]) == "warn"]
        print(f"{'PASS' if not blocking_fail else 'FAIL'}  {entry['file']:42s} {entry['bbox_mm']}  small-part:{small['status']:14s} warn:{warns}")
        for c in blocking_fail:
            print("   FAIL", c["id"], c["detail"])
    manifest["parts"].append({"id": "sparkle_skin", "name": "Sparkle Skin", "type": "Skin", "line": "snap", "size_class": "n/a",
                              "stat": "Style", "behavior": "Glitter texture in AR and game", "prints": False, "file": None, "tags": ["skin"],
                              "connectors": [], "safety": {"small_part_status": "above_cylinder", "print_page_warning": ["Game and AR only. Never printed."]},
                              "print": {"orientation": "n/a"}, "checks": []})
    # a check that applies to a part must be emitted for it; nothing undefined may appear; a check that applies to no part yet is dormant
    real = [p for p in manifest["parts"] if p.get("file")]
    emitted = {c["id"] for p in manifest["parts"] for c in p["checks"]}
    undefined = emitted - set(IF["checks"])
    missing = [(p["id"], cid) for p in real for cid in IF["checks"] if check_applies(cid, p["connectors"], p.get("family")) and cid not in {c["id"] for c in p["checks"]}]
    extra = [(p["id"], c["id"]) for p in real for c in p["checks"] if not check_applies(c["id"], p["connectors"], p.get("family"))]
    if undefined or missing or extra:
        raise SystemExit(f"checks out of sync with interfaces.json: undefined={sorted(undefined)} missing={missing[:4]} not-applicable-but-emitted={extra[:4]}")
    dormant = sorted(set(IF["checks"]) - emitted)
    if dormant:
        print("dormant checks (apply to no part yet; tested with fixtures):", ", ".join(dormant))
    (out / "toyventor_parts.json").write_text(json.dumps(manifest, indent=2))
    import toyventor_index
    toyventor_index.write(out, manifest)
    return all_ok


if __name__ == "__main__":
    sys.exit(0 if main(sys.argv[1] if len(sys.argv) > 1 else "out") else 1)
