    b, fam, size = row["build"], row["family"], row["size"]
    if fam in FAMILIES:
        spec = FAMILIES[fam](row)
    elif fam == "forge_mount":
        mount_args = {"face": b["face"], "n": b.get("n", 3), "outline": b.get("outline", "square"), "outer_d": b.get("outer_d"), "hole_d": b.get("hole_d")}
