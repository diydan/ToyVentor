# W3 originals, drawn in mm for a Small 2x2 foot (scale multiplies the body for other sizes). Every face leans inward or is
# vertical, so nothing hangs over more than 45 degrees.
def _s(size, scale):
    return scale * STUD[size]["pitch"] / STUD["small"]["pitch"]


def bumper_horns(size="small", grid=(2, 2), scale=1.0, base="foot", pad=None, lock=False):
    p, fh, foot = _foot(size, grid, base, pad)
    s = _s(size, scale)
    horns = []
    for side in (-1, 1):
        pts = []
        for i in range(9):
            t = i / 8
            pts.append(sph((4.2 - 2.4 * t) * s, (side * (5.0 + 8.0 * t ** 1.3) * s, 0, fh + 17.0 * t * s)))
        horns += [Manifold.batch_hull([u, v]) for u, v in zip(pts, pts[1:])]
    return _finish(size, grid, foot, lock, union(horns), fh, base)


def pointy_ears(size="small", grid=(2, 2), scale=1.0, base="foot", pad=None, lock=False):
    p, fh, foot = _foot(size, grid, base, pad)
    s = _s(size, scale)
    T = 3.2 * s
    prof = CrossSection([[(-4.8 * s, -3.0 * s), (4.8 * s, -3.0 * s), (1.0 * s, 17.0 * s), (-1.0 * s, 17.0 * s)]])   # base buried: the lean lifts one corner.offset(-1.0 * s, 1, 2, 24).offset(1.0 * s, 1, 2, 24)
    ear = Manifold.extrude(prof, T).rotate((90, 0, 0)).translate((0, T / 2, 0))      # profile in x-z, thickness along y
    ears = None
    for side in (-1, 1):
        e = ear.rotate((0, side * 10.0, 0)).translate((side * 6.4 * s, 0, fh))       # leaned 10 degrees outward
        ears = e if ears is None else ears + e
    return _finish(size, grid, foot, lock, ears, fh, base)


def wobble_hat(size="small", grid=(2, 2), scale=1.0, base="foot", pad=None, lock=False):
    p, fh, foot = _foot(size, grid, base, pad)
    s = _s(size, scale)
    W = min(grid) * p["pitch"] - 2 * p["gap"]
    brim_r = W / 2 - 0.8
    cone_r = 8.5 * s
    if base == "integrated":                   # brim stops short of the neighbouring studs, so it needs no notches
        brim_r = p["pitch"] - p["stud_d"] / 2 - 0.6
        cone_r = brim_r - 1.2
    brim = cyl(1.6 * s + 0.5, brim_r, fh - 0.5)
    lean, H = math.radians(10), 24.0 * s
    cone = Manifold.batch_hull([cyl(0.6, cone_r, fh + 1.0 * s), sph(1.4 * s, (0, H * math.sin(lean), fh + 1.0 * s + H * math.cos(lean)))])
    return _finish(size, grid, foot, lock, brim + cone, fh, base)


def ridge_fin(size="small", grid=(2, 2), scale=1.0, base="foot", pad=None, lock=False):
    p, fh, foot = _foot(size, grid, base, pad)
    s = _s(size, scale)
    T = 3.0 * s
    lead = [(-10.5 * s + 16.5 * s * t, 20.0 * s * t ** 0.8) for t in [i / 12 for i in range(13)]]
    # Base buried 2 mm so the rounding below only touches the trimmed-off part; the rounding gives the apex a 1 mm radius (a needle apex is
    # narrower than the nozzle for several layers and does not print).
    prof = CrossSection([[(-10.5 * s, -2.0), (10.5 * s, -2.0)] + lead[::-1]]).offset(-1.0 * s, 1, 2, 24).offset(1.0 * s, 1, 2, 24)
    fin = Manifold.extrude(prof, T).rotate((90, 0, 90)).translate((-T / 2, 0, fh))       # profile in y-z, thickness along x
    return _finish(size, grid, foot, lock, fin, fh, base)


def bounce_capsule(size="small", grid=(2, 2), scale=1.0, base="foot", pad=None, lock=False, coils=1):
    p, fh, foot = _foot(size, grid, base, pad)
    s = _s(size, scale)
    ro, ri, z = 7.5 * s, 6.0 * s, fh
    prof = [(0.0, fh - 0.5), (ro, fh - 0.5), (ro, z)]
    for _ in range(coils):                     # bellows: in at 37 deg, out at 31 deg from vertical, both rising
        prof += [(ri, z + 2.0 * s), (ro, z + 4.5 * s)]
        z += 4.5 * s
    prof += [(0.0, z)]
    bellows = Manifold.revolve(CrossSection([np.array(prof)]), 64)
    ball = Manifold.batch_hull([cyl(0.6, 7.0 * s, z - 0.6), sph(8.5 * s, (0, 0, z + 7.0 * s))])
    return _finish(size, grid, foot, lock, bellows + ball, fh, base)


