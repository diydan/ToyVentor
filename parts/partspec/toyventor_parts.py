def mount_layout(face, hole_d=None, n=3, outline="square", outer_d=None):
    """Where a Forge Mount's studs or bores go. Square: an n x n grid. Round: a disc outer_d across (from the scan) filled with every lattice
    position whose stud or bore fits inside the rim. Either way, positions too close to the attach hole are left out.
    Returns dict(size, pitch, n, c0, keep, omit, feat_r, rim, hole_d, R)."""
    fm = IF["forge_mount"]
    hole_d = fm["attach"]["hole_d_default_mm"] if hole_d is None else hole_d     # 0 = no scan hole (the face sits on a shoe)
    pro_face = face == "bore_grid"
    if pro_face:
        size, pitch, feat_r, rim = "pro", IF["lattice"]["unit_mm"], pro.BORE["free_d"] / 2, 2.0
    else:
        size = face.split("_")[1]
        p = STUD[size]
        size, pitch, feat_r, rim = size, p["pitch"], p["stud_d"] / 2, p["wall"]
    clear = (hole_d / 2 + fm["attach"]["lead_in_mm"] + 0.5 + feat_r) if hole_d else 0.0   # nearest a stud or bore centre may come to the hole axis

    def grid(n, R):
        c0 = (n - 1) / 2                                                      # odd n: positions on the axis lattice; even n: offset half a pitch
        keep, omit = [], []
        for i in range(n):
            for j in range(n):
                d = math.hypot((i - c0) * pitch, (j - c0) * pitch)
                ok = d >= clear and (R is None or d + feat_r + rim <= R + 1e-9)
                (keep if ok else omit).append([i, j])
        return {"size": size, "pitch": pitch, "n": n, "c0": c0, "keep": keep, "omit": omit, "feat_r": feat_r, "rim": rim, "hole_d": hole_d, "R": R}
    if outline == "round":
        if not outer_d:
            raise ValueError("a round Forge Mount needs outer_d (from the scan)")
        R = outer_d / 2
        reach = (R - rim - feat_r) / pitch
        options = [grid(2 * int(reach) + 1, R)] + ([] if pro_face else [grid(2 * int(reach + 0.5), R)])   # studs may take either lattice phase; Pro bores stay whole TU from the axis
        L = max(options, key=lambda g: (seat_count(g) if not pro_face else 0, len(g["keep"])))
    else:
        L = grid(n, None)
    if len(L["keep"]) < 4:
        raise ValueError(f"forge mount ({face}, {outline}): {'hole ' + str(hole_d) + ' mm leaves ' if hole_d else 'only '}fewer than 4 {'bores' if pro_face else 'studs'}; use a larger mount")
    if not pro_face and seat_count(L) < 3:
        raise ValueError(f"forge mount ({face}, {outline}): a 2x2 part would sit on {seat_count(L)} stud(s); needs at least 3. Use a larger mount")
    return L


def seat_count(L):
    """Most kept studs under any 2x2 group: what a 2x2 add-on can grip on this mount."""
    kept = {tuple(c) for c in L["keep"]}
    return max([sum((i + a, j + b) in kept for a in (0, 1) for b in (0, 1)) for i in range(L["n"] - 1) for j in range(L["n"] - 1)] or [0])


def mount_seat_offset(L):
    """Centre of the 2x2 group of kept studs a reference part seats on: the group with the most studs, first in grid order."""
    kept = {tuple(c) for c in L["keep"]}
    best = max(((i, j) for i in range(L["n"] - 1) for j in range(L["n"] - 1)), key=lambda g: sum((g[0] + a, g[1] + b) in kept for a in (0, 1) for b in (0, 1)))
    return ((best[0] - L["c0"] + 0.5) * L["pitch"], (best[1] - L["c0"] + 0.5) * L["pitch"])


def _mount_body(L, h, edge_r, chamfer):
    if L["R"] is None:
        W = L["n"] * L["pitch"] - (0 if L["size"] == "pro" else 2 * STUD[L["size"]]["gap"])
        return rbox(W, W, h, edge_r, chamfer)
    R = L["R"]                                     # disc with the same small bed chamfer as every other part
    return Manifold.batch_hull([Manifold.cylinder(0.01, R - chamfer, R - chamfer, 128), Manifold.cylinder(h - chamfer, R, R, 128).translate((0, 0, chamfer))])


def _mount_hole_and_ribs(body, L, h, fm):
    lead, hole_d = fm["attach"]["lead_in_mm"], L["hole_d"]
    body = body - cyl(h + 0.2, hole_d / 2, -0.1) - Manifold.cylinder(lead, hole_d / 2, hole_d / 2 + lead, SEG).translate((0, 0, h - lead))
    for k in range(fm["attach"]["crush_ribs"]):
        rib = Manifold.cube((fm["attach"]["rib_w_mm"], fm["attach"]["rib_h_mm"], h - 1.8)).translate((-fm["attach"]["rib_w_mm"] / 2, hole_d / 2 - 0.5 - 0.7, 0.0))
        body = body + rib.rotate((0, 0, 120 * k))
    return body


def mount_join_points(L):
    """Where pins join a face to its shoe: up to one point per quadrant, as far out as fits. Small faces use the centres of 2x2 stud groups
    (between four studs, clear of them all); Pro faces use their own bores."""
    sh = IF["forge_mount"]["shoe"]
    if L["size"] == "pro":
        cands = [((i - L["c0"]) * L["pitch"], (j - L["c0"]) * L["pitch"]) for i, j in L["keep"]]
    else:
        p = STUD[L["size"]]
        kept = {tuple(c) for c in L["keep"]}
        cands = [((i - L["c0"] + 0.5) * L["pitch"], (j - L["c0"] + 0.5) * L["pitch"]) for i in range(L["n"] - 1) for j in range(L["n"] - 1)
                 if all((i + a, j + b) in kept for a in (0, 1) for b in (0, 1))]
        hole_r = pro.BORE["free_d"] / 2
        cands = [c for c in cands if L["pitch"] / math.sqrt(2) >= p["stud_d"] / 2 + hole_r + sh["join_wall_mm"]]
        if L["R"] is not None:
            cands = [(x, y) for x, y in cands if math.hypot(x, y) + hole_r + sh["join_wall_mm"] + 0.5 <= L["R"]]
    best = {}
    for x, y in cands:
        q = (x >= 0, y >= 0)
        if x == 0 or y == 0:
            continue
        if q not in best or math.hypot(x, y) > math.hypot(*best[q]):
            best[q] = (x, y)
    return sorted(best.values())


def _join_conn(points, depth, z0, cid):
    """Join holes as a bore connector: a grid on the 1/8 TU lattice from the axis, holding only the join points."""
    TU = IF["lattice"]["unit_mm"]
    step = TU / 8
    xs, ys = sorted({x for x, _ in points}), sorted({y for _, y in points})
    px = (xs[-1] - xs[0]) if len(xs) > 1 else TU
    py = (ys[-1] - ys[0]) if len(ys) > 1 else TU
    assert abs(px - py) < 1e-6 or len(xs) == 1 or len(ys) == 1, "join points must sit on a square"
    pitch = max(px, py)
    nx, ny = len(xs), len(ys)
    omit = [[i, j] for i in range(nx) for j in range(ny) if (xs[i], ys[j]) not in set(points)]
    g = {"nx": nx, "ny": ny, "pitch": round(pitch / step) * step, "anchor": "corner"}
    if omit:
        g["omit_cells"] = omit
    return {"id": cid, "kind": "bore_grid", "gender": "F", "interface": "bore_grid", "size_class": "pro", "fit_class": "PIN", "bore_class": "free",
            "depth_mm": depth, "lattice": "axis8", "frame": {"origin": [xs[0], ys[0], z0], "normal": [0, 0, 1]}, "grid": g}


def forge_mount(face="stud_large", hole_d=None, n=3, outline="square", outer_d=None, join_pins=False):
    """THE Forge Mount: one part family for both lines. The face picks the connector (Small studs, Large studs or Pro bores); the outline is
    square (n x n) or round (outer_d from the scan, filled with every lattice position that fits)."""
    fm = IF["forge_mount"]
    L = mount_layout(face, hole_d, n, outline, outer_d)
    lead = fm["attach"]["lead_in_mm"]
    attach = {"id": "scan_attach", "kind": "bore", "gender": "F", "interface": "forge_mount.attach", "size_class": L["size"], "role": "scan_attach",
              "frame": {"origin": [0, 0, 0], "normal": [0, 0, 1]}, "bore": {"d_mm": L["hole_d"], "lead_in_mm": lead}}
    extras = {"mount_frame": {"origin": [0, 0, 0], "z": [0, 0, 1]}, "mount_outline": {"shape": outline, **({"outer_d_mm": round(2 * L["R"], 3)} if L["R"] else {})}}
    if face == "bore_grid":
        return _forge_mount_pro(L, fm, attach, extras, join_pins)
    p = STUD[L["size"]]
    h = p["plate_h"]
    body = _mount_body(L, h, p["edge_r"], p["bed_chamfer"])
    st = stud(p)
    for i, j in L["keep"]:
        body = body + st.translate(((i - L["c0"]) * L["pitch"], (j - L["c0"]) * L["pitch"], h))
    conns = [stud_conn(L["size"], L["n"], L["n"], h, omit=L["omit"])]
    if L["hole_d"]:
        body = _mount_hole_and_ribs(body, L, h, fm)
        conns.append(attach)
    if join_pins:
        if L["size"] == "large":
            raise ValueError("Large faces are for under-3s: a pin that can be pulled out is a small part. Join a Large face to its shoe permanently.")
        pts = mount_join_points(L)
        if len(pts) < 3:
            raise ValueError(f"forge mount ({face}, {outline}): room for only {len(pts)} join pin(s) between the studs; use a larger face")
        for x, y in pts:
            body = body - pro.bore_cutter("free", h, x, y)
        conns.append(_join_conn(pts, h, 0.0, "join"))
        extras["join_pins"] = len(pts)
    return body, conns, extras


def _forge_mount_pro(L, fm, attach, extras, join_pins=False):
    """Forge Mount with the Pro face: a 1 TU plate with free bores on the kept lattice positions. Square plates put bores on cell centres;
    round plates put them on whole-TU positions from the mount axis (lattice 'centre')."""
    TU, T = IF["lattice"]["unit_mm"], pro.BEAM["section_tu"] * IF["lattice"]["unit_mm"]
    body = _mount_body(L, T, pro.BEAM["fillet_outer_mm"], pro.BEAM["bed_chamfer_mm"])
    for i, j in L["keep"]:
        body = body - pro.bore_cutter("free", T, (i - L["c0"]) * TU, (j - L["c0"]) * TU)
    if L["hole_d"]:
        body = _mount_hole_and_ribs(body, L, T, fm)
    conn = {"id": "bores", "kind": "bore_grid", "gender": "F", "interface": "bore_grid", "size_class": "pro", "fit_class": "PIN", "bore_class": "free", "depth_mm": T,
            "frame": {"origin": [-L["c0"] * TU, -L["c0"] * TU, 0.0], "normal": [0, 0, 1]}, "grid": {"nx": L["n"], "ny": L["n"], "pitch": TU, "anchor": "corner", "omit_cells": L["omit"]}}
    if L["R"] is not None:
        conn["lattice"] = "centre"
    attach["size_class"] = "pro"
    if join_pins:
        extras["join_pins"] = len(mount_join_points(L))          # pins go through the face's own bores
    return body, [conn] + ([attach] if L["hole_d"] else []), extras


def snap_pro_adapter():
    """Bridges the lines: a 3 x 3 TU plate, 1 TU thick, with Pro free bores on the 3 x 3 cell centres and a Small 2 x 2 stud grid on top,
    sitting on the inner cell corners so every stud stands on solid plate between four bores."""
    TU, T = IF["lattice"]["unit_mm"], pro.BEAM["section_tu"] * IF["lattice"]["unit_mm"]
    p = STUD["small"]
    body = rbox(3 * TU, 3 * TU, T, pro.BEAM["fillet_outer_mm"], pro.BEAM["bed_chamfer_mm"])
    for i in (-1, 0, 1):
        for j in (-1, 0, 1):
            body = body - pro.bore_cutter("free", T, i * TU, j * TU)
    st = stud(p)
    for i in (-0.5, 0.5):
        for j in (-0.5, 0.5):
            body = body + st.translate((i * TU, j * TU, T))
    bores = {"id": "bores", "kind": "bore_grid", "gender": "F", "interface": "bore_grid", "size_class": "pro", "fit_class": "PIN", "bore_class": "free", "depth_mm": T,
             "frame": {"origin": [-TU, -TU, 0.0], "normal": [0, 0, 1]}, "grid": {"nx": 3, "ny": 3, "pitch": TU, "anchor": "corner"}}
    return body, [stud_conn("small", 2, 2, T), bores], {}


def forge_shoe(face="stud_small", outline="round", outer_d=64.0, n=5, surface="cylinder", radius_mm=20.0, clip=False):
    """The hugging half of a two-part Forge Mount. Its underside follows the toy's surface (stand-ins: a cylinder along x, or a sphere,
    crown at z = 0, plus a small gap); its top is flat at the face's footprint and carries blind join holes that line up with the face's join
    holes. It prints with the hugging face up, so nothing hangs over. Large faces cannot use pins (see interfaces.json forge_mount.shoe)."""
    if face == "stud_large":
        raise ValueError("Large faces are for under-3s: a pin that can be pulled out is a small part. Join a Large face to its shoe permanently.")
    sh = IF["forge_mount"]["shoe"]
    L = mount_layout(face, 0.0, n, outline, outer_d)
    pts = mount_join_points(L)
    if len(pts) < 3:
        raise ValueError(f"forge shoe ({face}, {outline}): room for only {len(pts)} join pin(s); use a larger face")
    TU = IF["lattice"]["unit_mm"]
    depth = TU if face == "bore_grid" else STUD[L["size"]]["plate_h"]        # pin length is twice this: half in the face, half in the shoe
    T = depth + sh["skin_mm"]
    R, g = radius_mm, sh["gap_mm"]
    if L["R"] is not None:
        half, prism = L["R"], lambda h, z: Manifold.cylinder(h, L["R"], L["R"], 128).translate((0, 0, z))
        reach = L["R"]
    else:
        W = L["n"] * L["pitch"] - (0 if L["size"] == "pro" else 2 * STUD[L["size"]]["gap"])
        half, prism = W / 2, lambda h, z: Manifold.cube((W, W, h)).translate((-W / 2, -W / 2, z))
        reach = W / 2 * (math.sqrt(2) if surface == "sphere" else 1.0)
    sag = R if reach >= R else R - math.sqrt(R * R - reach * reach)
    if surface == "cylinder":
        toy = Manifold.cylinder(4 * half + 10, R + g, R + g, 192).rotate((0, 90, 0)).translate((-2 * half - 5, 0, -R))
    else:
        toy = Manifold.sphere(R + g, 192).translate((0, 0, -R))
    clip_info = None
    if clip:
        if surface != "cylinder":
            raise ValueError("a clip-on shoe wraps a limb or tail (a cylinder); round bodies need glue or a strap")
        body, clip_info = _clip_body(R, g, T, half, prism)
    else:
        body = prism(T + sag, -sag) - toy                          # top exactly at T, where the face sits
    for x, y in pts:
        body = body - pro.bore_cutter("free", depth, x, y, T - depth)
    tm = to_trimesh(body)                                          # how much of the underside actually touches the toy
    c, a, nrm = tm.triangles_center, tm.area_faces, tm.face_normals
    d = (np.hypot(c[:, 1], c[:, 2] + R) if surface == "cylinder" else np.linalg.norm(c - np.array([0, 0, -R]), axis=1)) - (R + g)
    contact = float(a[(np.abs(d) < 0.3) & (nrm[:, 2] < 0)].sum())
    hug = {"surface": surface, "radius_mm": R, "gap_mm": g, "contact_mm2": round(contact, 1), "face": face, "join_pins": len(pts), "pin_length_mm": 2 * depth}
    if clip_info:
        hug["clip"] = clip_info
    return body, [_join_conn(pts, depth, T - depth, "join")], {"print_rotation_deg": [180, 0, 0], "hug": hug}


def _clip_strain(R, g, t, gamma_deg, hug_half_deg):
    """Curved-beam estimate of the peak bending strain when the clip's arms open to pass the limb: each arm must open by
    (R + g)(1 - cos gamma); the free arc runs from the end of the hug (hug_half) to the lip (90 + gamma)."""
    gm = math.radians(gamma_deg)
    delta = (R + g) * (1 - math.cos(gm))
    rm = R + g + t / 2
    free = 2 * math.radians(90 + gamma_deg - hug_half_deg)
    return t * (2 * delta) / (2 * rm * rm * free), delta


def _clip_body(R, g, T, half, prism):
    """Profile across the limb: the platform (flat top for the face) hugs the top of the limb over +/- hug_half degrees; below it a C wall of
    thickness t wraps on to 90 + gamma degrees each side and leaves an opening narrower than the limb. Extruded along the limb and trimmed to the
    face's outline."""
    cl = IF["forge_mount"]["shoe"]["clip"]
    t, hh = cl["wall_mm"], cl["hug_half_deg"]
    gamma = next((gd for gd in range(cl["gamma_max_deg"], cl["gamma_min_deg"] - 1, -1) if _clip_strain(R, g, t, gd, hh)[0] * 100 <= cl["max_strain_pct"]), None)
    if gamma is None:
        raise ValueError(f"no clip for a {2 * R:.0f} mm limb: even a {cl['gamma_min_deg']} degree wrap would strain the arms past {cl['max_strain_pct']}%; use glue or a strap")
    strain, delta = _clip_strain(R, g, t, gamma, hh)
    if delta < cl["min_snap_mm"]:
        raise ValueError(f"no clip for a {2 * R:.1f} mm limb: a clip that does not overstrain would grip only {delta:.2f} mm per side, "
                         f"less than {cl['min_snap_mm']} mm; use glue or a strap")
    rg, ro = R + g, R + g + t
    reach = 90 + gamma
    wedge = CrossSection([[(0.0, 0.0)] + [(3 * ro * math.sin(math.radians(a)), 3 * ro * math.cos(math.radians(a))) for a in range(reach, -reach - 1, -2)]])   # counter-clockwise
    if wedge.area() <= 0:
        raise AssertionError("clip wedge is empty")
    ring = (CrossSection.circle(ro, 192) - CrossSection.circle(rg, 192)) ^ wedge
    z_pb = ro * math.cos(math.radians(hh))                         # platform bottom, measured from the limb's centre
    plat = CrossSection.square((2 * half, T + R - z_pb + 0.01)).translate((-half, z_pb))
    prof = ((ring + plat) - CrossSection.circle(rg, 192)).translate((0, -R))
    L = 2 * half
    body = Manifold.extrude(prof, L).rotate((90, 0, 90)).translate((-L / 2, 0, 0))
    body = body ^ prism(T + 2 * R + t + 2, -2 * R - t - 1)
    opening = 2 * rg * math.cos(math.radians(gamma))
    return body, {"wrap_deg": 2 * reach, "opening_mm": round(opening, 2), "limb_d_mm": round(2 * rg, 2), "snap_mm_per_side": round(delta, 2),
                  "est_strain_pct": round(strain * 100, 2), "wall_mm": t}


