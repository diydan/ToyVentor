def cyl(h, r, z=0.0, x=0.0, y=0.0, seg=SEG):
    return Manifold.cylinder(h, r, r, seg).translate((x, y, z))


def ellipsoid(a, b, c, center):
    return Manifold.sphere(1.0, 48).scale((a, b, c)).translate(center)


def sph(r, center):
    return Manifold.sphere(r, 48).translate(center)


def union(parts):
    return Manifold.batch_boolean(parts, 0)


def keep_above(m, z):
    return m ^ Manifold.cube((500, 500, 500)).translate((-250, -250, z))


def stud(p):
    r, h = p["stud_d"] / 2, p["stud_h"]
    f = min(0.6, h / 3)
    prof = [(0.0, 0.0), (r, 0.0), (r, h - f)]
    for i in range(1, 7):
        a = math.radians(90 * i / 6)
        prof.append((r - f + f * math.cos(a), h - f + f * math.sin(a)))
    prof.append((0.0, h))
    return Manifold.revolve(CrossSection([np.array(prof)]), FIT_SEG)


def tube_dims(p):
    gap = p["pitch"] * math.sqrt(2) - p["stud_d"]
    return (p["stud_d"] + p["fit"]) / 2, (gap - p["fit"]) / 2


def block(size, nx, ny, h, top, studs=True):
    p = STUD[size]
    W, D = nx * p["pitch"] - 2 * p["gap"], ny * p["pitch"] - 2 * p["gap"]
    wall = p["wall"]
    body = rbox(W, D, h, p["edge_r"], p["bed_chamfer"])
    cav = Manifold.cube((W - 2 * wall, D - 2 * wall, h - top + 0.1)).translate((-(W / 2 - wall), -(D / 2 - wall), -0.1))
    body = body - cav
    ri, ro = tube_dims(p)
    if nx >= 2 and ny >= 2:
        for i in range(1, nx):
            for j in range(1, ny):
                x, y = (i - nx / 2) * p["pitch"], (j - ny / 2) * p["pitch"]
                body = body + (cyl(h - top + 0.2, ro, 0, x, y, FIT_SEG) - cyl(h - top + 0.1, ri, -0.1, x, y, FIT_SEG))
    if studs:
        s = stud(p)
        for i in range(nx):
            for j in range(ny):
                body = body + s.translate(((i + 0.5 - nx / 2) * p["pitch"], (j + 0.5 - ny / 2) * p["pitch"], h))
    return body


