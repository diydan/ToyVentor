    hy = pro.BORE["shaft_flats"] / 2
    grip = pro.pin_solid("flats", L + 6.0)
    cz = L + 19.0
    pts = []
    for k in range(10):
        ang = math.radians(90 + k * 36)
        r = 18.5 if k % 2 == 0 else 9.8
        pts.append((r * math.cos(ang), cz + r * math.sin(ang)))
    neck_cs = CrossSection.square((6.2, 10.0), center=True).translate((0.0, L + 4.5))
    star_cs = (CrossSection([np.array(pts)]) + neck_cs).offset(-1.6, JoinType.Round).offset(1.6, JoinType.Round)
    base_plate = _xz_to_layflat(star_cs, hy)
    inner_star_cs = star_cs.offset(-2.4, JoinType.Round)
    spark_hub_cs = CrossSection.circle(6.2, 48).translate((0.0, cz))
    crest_star = Manifold.extrude(inner_star_cs, 2.2).rotate((90, 0, 0)).translate((0.0, hy + 1.2, 0.0))
    crest_hub = Manifold.extrude(spark_hub_cs, 3.0).rotate((90, 0, 0)).translate((0.0, hy + 2.0, 0.0))
