def flare_clip(body, base_outline, z_top):
    """Trim body to a 41 degree flare rising from base_outline (the base's real outline at z_top, its cut plane). The flare starts 0.3 mm
    outside that outline (well inside the 1 mm overhang allowance, and offset so the surfaces never coincide), so no part of the body
    starts as a one-sided ledge over air."""
    z0 = z_top - 0.5
    flare = Manifold.batch_hull([Manifold.extrude(base_outline.offset(-0.14, JoinType.Round), 0.01).translate((0, 0, z0)),
                                 Manifold.extrude(base_outline.offset(-0.14 + 70.0, JoinType.Round), 0.01).translate((0, 0, z0 + 80.0))])
    return body ^ flare


