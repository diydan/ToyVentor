def _foot(size, grid, base="foot", pad=None):
    p = STUD[size]
    if base == "integrated":                   # no base plate: the body starts on the bed (or on a small pad) and carries its own stud holes
        if not pad:
            return p, 0.0, None
        r, h = (p["stud_d"] + p["fit"]) / 2 + p["wall"] + 0.6, p["stud_h"] + 0.4 + 1.6
        disc = [CrossSection.circle(r, 64).translate((a * p["pitch"], b * p["pitch"])) for a, b in pad]
        return p, h, Manifold.extrude(CrossSection.batch_hull(disc), h)   # pad: hull of discs on the given lattice points, just deep enough for the holes
    return p, p["plate_h"], block(size, *grid, p["plate_h"], p["plate_top"], studs=False)


def _finish(size, grid, foot, lock, body, fh, base):
    if base == "integrated":
        shape = keep_above(body, fh - 0.5) + foot if foot is not None else keep_above(body, 0.0)
        return integrated_sockets(shape, size, lock)
    return foot + keep_above(body, fh - 0.5), [socket_conn(size, *grid)], {}


def integrated_sockets(body, size, lock=False):
    """Base 'integrated': no plate around the part. Stud holes are cut into the underside of the part's own shape (or its small pad)
    wherever it is wide enough to wrap a hole with a full wall; where a stud of a plate below would only clip the shape, a relief is cut so
    the part sits flat on any plate. Holes are the stud diameter plus the fit, so the stud fit is the same 0.05 mm as in a tube cage.
    The hole grid may sit on or half a pitch off the part's axis, independently in x and y, whichever gives the most full holes.
    lock: the part's direction matters, so it needs two holes, or one hole plus a relief that keys it against a neighbouring stud."""
    p = STUD[size]
    pitch, hole_r, wall, depth = p["pitch"], (p["stud_d"] + p["fit"]) / 2, p["wall"], p["stud_h"] + 0.4
    fp = body.slice(0.05)
    if fp.is_empty():
        raise ValueError("integrated base: the part has no flat underside on the bed")
    x0, y0, x1, y1 = fp.bounds()
    best = None
    for px in (0.0, 0.5):
        for py in (0.0, 0.5):
            full, relief = [], []
            for i in range(math.floor(x0 / pitch - px) - 1, math.ceil(x1 / pitch - px) + 2):
                for j in range(math.floor(y0 / pitch - py) - 1, math.ceil(y1 / pitch - py) + 2):
                    x, y = (i + px) * pitch, (j + py) * pitch
                    if (fp ^ CrossSection.circle(p["stud_d"] / 2 + 0.3, 48).translate((x, y))).area() < 0.01:
                        continue                                              # no stud of a plate below would touch the part here
                    ring = CrossSection.circle(hole_r + wall, 64).translate((x, y))
                    (full if (ring - fp).area() < 0.05 else relief).append((x, y))
            key = (len(full), -len(relief))
            if best is None or key > best[0]:
                best = (key, full, relief)
    _, full, relief = best
    if not full:
        raise ValueError("integrated base: no room for a single stud hole with a full wall; the shape needs a small pad")
    if lock and len(full) < 2 and not relief:
        raise ValueError("integrated base: this part's direction matters but it would swivel on one stud; give it a pad for a second hole")
    roof = LIM["min_roof_mm"]                                 # every hole gets a closed roof: where the shape is too thin above a hole, a boss
    inner = fp.offset(-0.05, JoinType.Round)                  # clipped just inside the footprint, so it never grazes the outer surface
    foot_prism = Manifold.extrude(inner, depth + roof)
    for x, y in full:                                         # full holes only: reliefs are edge clearance cuts, open at the side anyway
        disk = CrossSection.circle(hole_r, 64).translate((x, y)) ^ inner
        if disk.is_empty():
            continue
        if all((disk - body.slice(depth + dz)).area() < 0.01 * disk.area() for dz in (0.05, roof - 0.05)):
            continue                                          # already roofed: leave the shape untouched
        body = body + (cyl(depth + roof, hole_r + wall, 0.0, x, y, FIT_SEG) ^ foot_prism)
    for x, y in full:
        body = body - cyl(depth + 0.01, hole_r, -0.01, x, y, FIT_SEG)
    for x, y in relief:                                       # a relief is open at the side: a flat ceiling there would be a ledge over air, so
        body = body - cyl(depth + 0.01, hole_r, -0.01, x, y, FIT_SEG) - Manifold.cylinder(hole_r, hole_r, 0.01, FIT_SEG).translate((x, y, depth))   # it gets a 45 degree cone roof
    nx = int(round(2 * max(abs(x) for x, _ in full) / pitch)) + 1
    ny = int(round(2 * max(abs(y) for _, y in full) / pitch)) + 1
    cells = {(int(round(x / pitch + nx / 2 - 0.5)), int(round(y / pitch + ny / 2 - 0.5))) for x, y in full}
    conn = socket_conn(size, nx, ny)
    conn["style"] = "holes"
    omit = [[i, j] for i in range(nx) for j in range(ny) if (i, j) not in cells]
    if omit:
        conn["grid"]["omit_cells"] = omit
    locked = len(full) >= 2 or bool(relief)
    return body, [conn], {"sockets": {"holes": len(full), "reliefs": len(relief), "locked": locked}}


def hole_positions(conn):
    g = conn["grid"]
    omit = {tuple(c) for c in g.get("omit_cells", [])}
    return [((i + 0.5 - g["nx"] / 2) * g["pitch"], (j + 0.5 - g["ny"] / 2) * g["pitch"]) for i in range(g["nx"]) for j in range(g["ny"]) if (i, j) not in omit]


# Bespoke add-ons and capsules. Each takes the size and grid of its foot and a body scale: the six first designs were drawn for the
# old 8 mm lattice (K) at one size, so a variant at another size passes scale = its foot width / the original foot width.
def waddle_tail(size="large", grid=(2, 2), scale=1.0, base="foot", pad=None, lock=False):
    p, fh, foot = _foot(size, grid, base, pad)
    k = K * scale
    n, L = 10, 44.0 * k
    pts, y, z = [], 0.0, fh
    for i in range(n + 1):
        t = i / n
        pts.append((y, z, (11.0 - 6.5 * t) * k))
        y -= math.sin(math.radians(40 * t)) * L / n
        z += math.cos(math.radians(40 * t)) * L / n
    segs = [Manifold.batch_hull([sph(r, (0, y, z)), sph(r2, (0, y2, z2))]) for (y, z, r), (y2, z2, r2) in zip(pts, pts[1:])]
    body = union(segs)
    if base == "integrated" and foot is not None:            # the base ball is wider than its pad: flare it up from the pad's outline
        body = flare_clip(body, foot.slice(fh - 0.5), fh - 0.5)
    return _finish(size, grid, foot, lock, body, fh, base)


def cloud_wings(size="small", grid=(2, 2), scale=1.0, base="foot", pad=None, lock=False):
    p, fh, foot = _foot(size, grid, base, pad)
    k = K * scale
    bury = ROOT_BURY * scale                    # tied to the wing thickness, so it scales with the body
    lobes = [(0 * k, 7 * k, 8.0 * k), (-7 * k, 15 * k, 6.5 * k), (7 * k, 15 * k, 6.5 * k), (0 * k, 21 * k, 6.0 * k)]
    cs = None
    for v, u, r in lobes:
        c = CrossSection.circle(r, 40).translate((v, u))
        cs = c if cs is None else cs + c
    root = CrossSection.square((14 * k, 8 * k)).translate((-7 * k, 0))
    # Buried root: the tilted root must not leave a shallow underside above the foot, so it extends below the seat
    # plane and keep_above() trims it flush.
    root_buried = CrossSection.square((14 * k, 8 * k + bury)).translate((-7 * k, -bury))
    cs = cs + root_buried
    for v, u, r in lobes[1:3]:
        cs = cs + CrossSection.batch_hull([root, CrossSection.circle(r, 40).translate((v, u))])
    cs = cs.offset(0.8, 1, 2, 24).offset(-0.8, 1, 2, 24)
    wing = Manifold.extrude(cs, 4.0 * k).rotate((90, 0, 90)).translate((-2.0 * k, 0, 0))
    right = wing.rotate((0, 35.0, 0)).translate((1.5 * k, 0, fh - 1.2))
    left = right.mirror((1, 0, 0))
    return _finish(size, grid, foot, lock, (right + left).simplify(0.01), fh, base)


