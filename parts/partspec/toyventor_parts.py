def overhang_area(tm):
    n, c, a = tm.face_normals, tm.triangles_center, tm.area_faces
    lim = -math.sin(math.radians(LIM["max_overhang_deg"]))
    down = (n[:, 2] < lim) & (c[:, 2] > LIM["first_layer_exclusion_mm"])
    bridge = down & (n[:, 2] < -0.98)
    return float(a[down & ~bridge].sum()), float(a[bridge].sum())


def bridge_span(size, nx, ny):
    p = STUD[size]
    W, D = nx * p["pitch"] - 2 * p["gap"] - 2 * p["wall"], ny * p["pitch"] - 2 * p["gap"] - 2 * p["wall"]
    _, ro = tube_dims(p)
    tubes = [((i - nx / 2) * p["pitch"], (j - ny / 2) * p["pitch"]) for i in range(1, nx) for j in range(1, ny)] if nx >= 2 and ny >= 2 else []
    xs, ys = np.meshgrid(np.linspace(-W / 2, W / 2, 120), np.linspace(-D / 2, D / 2, 120))
    d = np.minimum(W / 2 - np.abs(xs), D / 2 - np.abs(ys))
    for tx, ty in tubes:
        d = np.minimum(d, np.hypot(xs - tx, ys - ty) - ro)
    return float(2 * d.max())


def _dirs(n):
    i = np.arange(n) + 0.5
    phi, theta = np.arccos(1 - i / n), np.pi * (1 + 5 ** 0.5) * i
    return np.c_[np.cos(theta) * np.sin(phi), np.sin(theta) * np.sin(phi), np.cos(phi)]


def _proj_diam(pts, d):
    a = np.array([1.0, 0, 0]) if abs(d[0]) < 0.9 else np.array([0, 1.0, 0])
    u = np.cross(d, a)
    u /= np.linalg.norm(u)
    v = np.cross(d, u)
    q = pts @ np.c_[u, v]
    try:
        q = q[ConvexHull(q).vertices]
    except Exception:
        pass
    return 2 * float(nsphere.minimum_nsphere(q)[1]), float(np.ptp(pts @ d))


def small_part_status(tm):
    """Conservative: does ANY orientation fit the part inside the small-parts cylinder?
    Uses the longest allowed depth, so it over-flags rather than under-flags. A lab
    test is still required; this is a design-time screen."""
    cyl_ = IF["safety"]["small_parts_cylinder"]
    pts = np.asarray(tm.convex_hull.vertices)
    cands = list(_dirs(300)) + [np.eye(3)[i] for i in range(3)]
    try:
        cands += [np.asarray(tm.bounding_box_oriented.primitive.transform)[:3, i] for i in range(3)]
    except Exception:
        pass
    best, best_d = (1e9, 0.0), None
    for d in cands:
        dm, ln = _proj_diam(pts, np.asarray(d, float))
        if ln <= cyl_["depth_max_mm"] and dm < best[0]:
            best, best_d = (dm, ln), np.asarray(d, float)
    rng = np.random.default_rng(0)
    if best_d is not None:
        for scale in (0.15, 0.05, 0.02):
            for _ in range(40):
                d = best_d + rng.normal(0, scale, 3)
                d /= np.linalg.norm(d)
                dm, ln = _proj_diam(pts, d)
                if ln <= cyl_["depth_max_mm"] and dm < best[0]:
                    best, best_d = (dm, ln), d
    D = cyl_["diameter_mm"]
    diam = best[0]
    over_pct = (diam - D) / D * 100 if diam < 1e8 else 999.0   # >0: too big to fit; <0: fits with room
    if diam <= D:
        status = "small_part"
    elif over_pct <= IF["safety"]["marginal_pct"]:
        status = "marginal"
    else:
        status = "above_cylinder"
    return dict(status=status, min_enclosing_diameter_mm=round(min(diam, 999.0), 2), margin_pct=round(over_pct, 1))


