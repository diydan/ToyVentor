def racer_roof_rack(size="small", grid=(2, 2), scale=1.0, base="integrated", pad=None, lock=False):
    """Raised stud deck on a perimeter wall, four full-width legs and a cross brace. Each leg's foot carries a stud hole; the wall, legs and
    brace leave only short bridges under the deck, each anchored on solid supports. Studs on top take more parts."""
    p = STUD[size]
    s = _s(size, scale)
    hole_top = p["stud_h"] + 0.4 + LIM["min_roof_mm"]
    foot_r = (p["stud_d"] + p["fit"]) / 2 + p["wall"] + 0.6
    d0, hx = 7.0 * s, _half(size, grid[0])
    body = None
    for i in range(grid[0]):
        for j in range(grid[1]):
            x, y = (i - (grid[0] - 1) / 2) * p["pitch"], (j - (grid[1] - 1) / 2) * p["pitch"]
            leg = cyl(d0 + 0.5, foot_r, 0.0, x, y)          # full-width legs: a necked leg is a poor bridge anchor, and the wall hides the legs anyway
            body = leg if body is None else body + leg
    deck = Manifold.extrude(CrossSection.square((2 * hx, 2 * hx), center=True), 3.9 * s).translate((0, 0, d0))
    wall = (Manifold.extrude(CrossSection.square((2 * hx, 2 * hx), center=True), d0 + 0.5)
            - Manifold.extrude(CrossSection.square((2 * hx - 3.2 * s, 2 * hx - 3.2 * s), center=True), d0 + 1.0).translate((0, 0, -0.25)))   # perimeter wall: the deck edge never starts in mid-air
    deck = deck + wall
    brace = (Manifold.cube((2 * hx - 2.0, 1.6 * s, d0 + 0.5)).translate((-(hx - 1.0), -0.8 * s, 0))
             + Manifold.cube((1.6 * s, 2 * hx - 2.0, d0 + 0.5)).translate((-0.8 * s, -(hx - 1.0), 0)))      # cross brace between the stud holes
    m, conns, ex = integrated_sockets(body + deck + brace, size, lock)
    z = d0 + 3.9 * s
    for i in range(grid[0]):
        for j in range(grid[1]):
            m = m + stud(p).translate(((i - (grid[0] - 1) / 2) * p["pitch"], (j - (grid[1] - 1) / 2) * p["pitch"], z))
    return m, conns + [stud_conn(size, grid[0], grid[1], z)], ex


def racer_axle_block(size="small", grid=(2, 2), **_):
    """A Snap brick (15 mm tall) with studs on top and a free bore across it for the axle. The bore is a teardrop, so the brick prints
    upright with no supports; the axle (a flat shaft) turns in it."""
