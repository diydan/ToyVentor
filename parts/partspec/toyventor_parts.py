def design_gap(size):
    """Radial stud-to-tube clearance the interface asks for (half the diametral fit)."""
    return STUD[size]["fit"] / 2


def facet_allowance(size):
    """Most the measured gap can exceed the design gap because both outlines are inscribed polygons."""
    p = STUD[size]
    _, ro = tube_dims(p)
    return (p["stud_d"] / 2 + ro) * (1 - math.cos(math.pi / FIT_SEG))


def fit_verdict(rep, size):
    """Apply the tolerance numbers to a fit report. as_designed -> T1; in_window -> T2.
    window is the printer surface offset range (mm, same offset on both parts) that keeps every stud between the
    max-play and max-interference limits; the calibration print has to land inside it."""
    g0, fa = design_gap(size), facet_allowance(size)
    if not rep["studs"]:
        return {"as_designed": False, "in_window": False, "window": None, "allowed": None, "design_gap": g0}
    lo, hi = g0 - TOL["design_gap_tol_mm"], g0 + TOL["design_gap_tol_mm"] + fa
    shift_lo, shift_hi = rep["gap_max"] - TOL["max_play_mm"], rep["gap_min"] + TOL["max_interference_mm"]  # allowed e_male + e_female
    e2 = 2 * TOL["surface_error_calibrated_mm"]
    within_limits = rep["gap_max"] <= TOL["max_play_mm"] and rep["gap_min"] >= -TOL["max_interference_mm"]   # the design itself must be usable
    return {"as_designed": lo <= rep["gap_min"] and rep["gap_max"] <= hi and within_limits, "in_window": shift_lo <= -e2 and e2 <= shift_hi,
            "window": [round(shift_lo / 2, 3), round(shift_hi / 2, 3)], "allowed": [round(lo, 3), round(hi, 3)], "design_gap": g0}


def fit_info(rep, v):
    if not rep["studs"]:
        return {"studs_measured": 0, "design_gap_mm": v["design_gap"]}
    return {"studs_measured": rep["studs"], "design_gap_mm": v["design_gap"], "gap_min_mm": round(rep["gap_min"], 3),
            "gap_max_mm": round(rep["gap_max"], 3), "surface_offset_window_mm": v["window"], "residual_error_mm": TOL["surface_error_calibrated_mm"]}


def fit_block(fit, size):
    if fit["kind"] == "snap":
        return fit_info(fit["rep"], fit_verdict(fit["rep"], size))
    if fit["kind"] == "mixed":
        sn, pr = fit_info(fit["rep"], fit_verdict(fit["rep"], fit["size"])), fit["summary"]["info"]
        w = [x for x in (sn.get("surface_offset_window_mm"), pr.get("surface_offset_window_mm")) if x]
        return {"studs_measured": sn.get("studs_measured", 0) + pr.get("studs_measured", 0), "design_gap_mm": min(sn["design_gap_mm"], pr["design_gap_mm"]),
                "gap_min_mm": min(sn["gap_min_mm"], pr["gap_min_mm"]), "gap_max_mm": max(sn["gap_max_mm"], pr["gap_max_mm"]),
                "surface_offset_window_mm": [max(x[0] for x in w), min(x[1] for x in w)], "residual_error_mm": TOL["surface_error_calibrated_mm"], "snap": sn, "pro": pr}
    return fit["summary"]["info"] if fit["kind"] == "pro" else {}


def level_of(check_id):
    """Severity is data: it lives in interfaces.json, never in code."""
    return IF["checks"][check_id]["level"]


def derive_status(checks, small, size_class):
    """verified iff no blocking check fails, the small-parts result is not marginal, and a Large part clears the cylinder.
    See interfaces.json conformance.status_rule."""
    if blocking_failures(checks) or small["status"] == "marginal":
        return "needs_reproportion"
    if size_class == "large" and small["status"] != "above_cylinder":
        return "needs_reproportion"
    return "verified"


def blocking_failures(checks):
    """Failing checks whose CURRENT level (from interfaces.json) is 'block'. Pending checks never count as passed or failed."""
    return [c for c in checks if level_of(c["id"]) == "block" and c["result"] == "fail"]


def hole_roof(m, conns):
    """Fraction of each integrated stud hole's ceiling covered by material, just above the ceiling and at the full roof height."""
    worst, n = 1.0, 0
    for c in conns:
        if c.get("style") != "holes":
            continue
        p = STUD[c["size_class"]]
        depth, r = p["stud_h"] + 0.4, (p["stud_d"] + p["fit"]) / 2
        for x, y in hole_positions(c):
            disk = CrossSection.circle(r, 64).translate((x, y))
            for dz in (0.05, LIM["min_roof_mm"] - 0.05):
                worst = min(worst, 1 - (disk - m.slice(depth + dz)).area() / disk.area())
            n += 1
    return worst > 0.99, f"{n} hole(s); least-covered roof {worst * 100:.0f}% (needs {LIM['min_roof_mm']} mm closed above every ceiling)"


def run_checks(part, m, tm, conns, small, fit, extras):
    out = []
    fam = part["family"]

    def add(cid, ok, detail=""):
        spec = IF["checks"][cid]
        result = "pending" if spec.get("pending") else ("pass" if ok else "fail")
        out.append({"id": cid, "level": spec["level"], "result": result, "detail": detail})

    def applies(cid):
        return check_applies(cid, conns, fam)

    bb = tm.bounds                                            # printed mesh: bed, overhang, bridge and size checks
    _b = m.bounding_box()
    abb = np.array([_b[:3], _b[3:]])                          # assembly frame: connector checks
    size = bb[1] - bb[0]
    add("G1_watertight", tm.is_watertight)
    add("G2_winding", tm.is_winding_consistent)
    bodies = len(tm.split(only_watertight=False))
    add("G3_single_body", bodies == 1, f"{bodies} body(ies)")
    add("G4_on_bed", abs(bb[0][2]) < 1e-3, f"zmin={bb[0][2]:.3f}")
    add("G5_fits_bed", all(size[i] <= LIM["bed_mm"][i] for i in range(3)), f"{size.round(1).tolist()} vs {LIM['bed_mm']}")
    steep, _ = overhang_area(tm)
    add("P1_no_supports", steep < LIM["steep_overhang_max_mm2"], f"{steep:.1f} mm2 steeper than {LIM['max_overhang_deg']} deg")
    if applies("P4_no_ledges"):
        import toyventor_ledge as _tl
        _tl.CANTILEVER_MM = LIM["ledge_cantilever_mm"]
        ledge_area, ledge_regions = _tl.ledges(tm, m, LIM["max_bridge_mm"], LIM["first_layer_exclusion_mm"])
        add("P4_no_ledges", ledge_area < LIM["ledge_max_mm2"],
            f"{ledge_area:.1f} mm2 of flat underside held on one side only" + (f"; worst at z {ledge_regions[0]['z_mm']} mm near {ledge_regions[0]['at_mm']}" if ledge_regions else ""))
    if part["cavity"]:
        sz, nx, ny, _, _ = part["cavity"]
        span = bridge_span(sz, nx, ny)
        add("P2_bridge_span", span <= LIM["max_bridge_mm"], f"{span:.1f} mm <= {LIM['max_bridge_mm']}")
    else:
        add("P2_bridge_span", True, "no cavity")
    unit = IF["lattice"]["unit_mm"]
    nest = lambda ratio: abs(ratio - round(ratio)) < 1e-6 or abs(1 / ratio - round(1 / ratio)) < 1e-6  # noqa: E731
    if part["size"] in STUD:
        p = STUD[part["size"]]
        add("P3_wall_min", p["wall"] >= LIM["min_wall_mm"], f"wall {p['wall']} mm vs minimum {LIM['min_wall_mm']}")
        ratio = p["pitch"] / unit
        add("I1_lattice", nest(ratio), f"pitch {p['pitch']} mm vs TU {unit} mm (ratio {ratio:.3f})")
    else:
        wall = (pro.BEAM["section_tu"] * unit - pro.BORE["free_d"]) / 2 if any(c["kind"] == "bore_grid" for c in conns) else None
        add("P3_wall_min", wall is None or wall >= LIM["min_wall_mm"], "no bores" if wall is None else f"wall {wall:.2f} mm vs minimum {LIM['min_wall_mm']}")
        pitches = sorted({c["grid"]["pitch"] for c in conns if c.get("grid")})
        add("I1_lattice", bool(pitches) and all(nest(x / unit) for x in pitches), f"pitch {pitches} mm vs TU {unit} mm")
    inside = True
    for c in conns:
        g = c.get("grid")
        if g:
            omitted = {tuple(o) for o in g.get("omit_cells", [])}
            for i in range(g["nx"]):
                for j in range(g["ny"]):
                    if (i, j) in omitted:                     # an omitted cell has no stud or hole, so it need not lie on the part
                        continue
                    if g.get("anchor") == "corner":
                        x, y = c["frame"]["origin"][0] + i * g["pitch"], c["frame"]["origin"][1] + j * g["pitch"]
                    else:
                        x, y = (i + 0.5 - g["nx"] / 2) * g["pitch"], (j + 0.5 - g["ny"] / 2) * g["pitch"]
                    inside &= (abb[0][0] <= x <= abb[1][0]) and (abb[0][1] <= y <= abb[1][1])
    add("I2_connectors_on_part", inside, f"{len(conns)} connector(s)")
    if applies("I7_hole_roof"):
        add("I7_hole_roof", *hole_roof(m, conns))
    if applies("I3_seats_on_reference"):
        ov = reference_overlap(part, m, conns)
        add("I3_seats_on_reference", ov < LIM["seat_overlap_max_mm3"], f"overlap {ov:.3f} mm3 with matching reference part")
    if applies("I4_bore_on_grid"):
        add("I4_bore_on_grid", *pro.bores_on_grid(conns, m, abb))
    if applies("I5_pin_fits_bore"):
        add("I5_pin_fits_bore", *pro.pins_and_bores_built_right(conns, m))
    if applies("I6_gear_on_grid"):
        add("I6_gear_on_grid", *pro.gear_on_grid(extras, abb, m))
    add("S1_small_part_screen", small["status"] == "above_cylinder",
        f"{small['status']}: best-fit diameter {small['min_enclosing_diameter_mm']} mm vs {IF['safety']['small_parts_cylinder']['diameter_mm']} mm cylinder")
    window = None
    if applies("T1_fit_as_designed"):
        E = TOL["surface_error_calibrated_mm"]
        if fit["kind"] == "snap":
            rep = fit["rep"]
            v = fit_verdict(rep, part["size"])
            window = v["window"]
            if rep["studs"]:
                add("T1_fit_as_designed", v["as_designed"], f"{rep['studs']} stud(s): gap {rep['gap_min']:+.3f} to {rep['gap_max']:+.3f} mm, design {v['design_gap']:.3f}, allowed {v['allowed'][0]:+.3f} to {v['allowed'][1]:+.3f}")
                add("T2_fit_tolerance_window", v["in_window"], f"surface offset window {v['window'][0]:+.3f} to {v['window'][1]:+.3f} mm vs calibrated error +/-{E}")
            else:
                add("T1_fit_as_designed", False, "no engaged studs found at the seat")
                add("T2_fit_tolerance_window", False, "no engaged studs found at the seat")
        elif fit["kind"] == "mixed":
            rep, sm = fit["rep"], fit["summary"]
            v = fit_verdict(rep, fit["size"])
            info = fit_block(fit, part["size"])
            window = info["surface_offset_window_mm"]
            add("T1_fit_as_designed", v["as_designed"] and sm["as_designed"], f"{rep['studs']} stud(s) gap {rep['gap_min']:+.3f} to {rep['gap_max']:+.3f} mm; {sm['measured']} pin/bore pair(s) gap {sm['info']['gap_min_mm']:+.3f} to {sm['info']['gap_max_mm']:+.3f} mm")
            add("T2_fit_tolerance_window", v["in_window"] and sm["in_window"], f"surface offset window {window[0]:+.3f} to {window[1]:+.3f} mm vs calibrated error +/-{E}")
        else:
            sm = fit["summary"]
            info = sm["info"]
            window = info.get("surface_offset_window_mm")
            add("T1_fit_as_designed", sm["as_designed"], (f"{sm['measured']} of {sm['listed']} pin/bore pair(s) measured: gap {info['gap_min_mm']:+.3f} to {info['gap_max_mm']:+.3f} mm"
                                                          if "gap_min_mm" in info else f"{sm['listed']} pair(s) listed, none measured (friction fit)"))
            add("T2_fit_tolerance_window", sm["in_window"], (f"surface offset window {window[0]:+.3f} to {window[1]:+.3f} mm vs calibrated error +/-{E}" if window else "not measured (friction fit)"))
    window_txt = f"printer surface offset must land in {window[0]:+.3f} to {window[1]:+.3f} mm" if window else "no window"
    add("F1_printed_fit", False, f"needs calibration print: {window_txt}")
    add("F2_breakage", False, "needs break/impact test: no piece may fit the cylinder after failure")
    return out


