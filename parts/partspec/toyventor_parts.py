def _organic_skull(H=28.8, w_max=44.4, d_max=36.8, z1=14.6, z2=20.4, crown_w=35.4, crown_d=25.8):
    """Crease-free C1 barrel-and-dome chibi skull matching Kip Classic's plump rounded back & cheeks (0 mm3 I3 plate clearance, < 3.5 deg per slice)."""
    w0, d0 = 30.4, 17.8
    slices = [
        (0.0,  28.4, 16.0, 0.0, 0.0),
        (0.35, 29.0, 16.4, 0.0, 0.0),
        (2.95, w0,   d0,   0.0, 0.0),
    ]
    # 1. C1-smooth lower cheek & occiput curve above stud_h = 2.80 mm (max slope 42.6 deg, glides to 0 deg at z1!)
    for k in range(1, 19):
        z = 2.95 + (z1 - 2.95) * (k / 18)
        s = _c1_ramp((z - 2.95) / (z1 - 2.95), f=0.28)
        slices.append((z, w0 + (w_max - w0) * s, d0 + (d_max - d0) * s, 0.0, 0.0))
    # 2. Plump Kip-Classic vertical barrel band across mid-cheeks, faceplate & rounded back
    for k in range(1, 6):
        z = z1 + (z2 - z1) * (k / 5)
        slices.append((z, w_max, d_max, 0.0, 0.0))
    # 3. True elliptical upper forehead & crown dome (cosine-spaced slices, < 3.5 deg per slice)
    for k in range(1, 15):
        t = k / 14
        q = math.sin(t * math.pi * 0.5)
        z = z2 + (H - z2) * q
        e = math.cos(t * math.pi * 0.5)
        slices.append((z, crown_w + (w_max - crown_w) * e, crown_d + (d_max - crown_d) * e, 0.0, 0.0))
    return _ellipse_chain(slices)


def _face_pocket_cutter(y_floor=-14.0625, z_c=14.0625, w_in=23.2, h_in=11.4, r_in=4.6):
    """Support-free 36-deg softly rounded front visor bezel pocket on -Y (zero ceiling overhang)."""
    dy = 5.4
    dz = 7.4
    dx = 6.0
    cs_in = rrect(w_in, h_in, r_in)
    cs_out = rrect(w_in + 2 * dx, h_in + 2 * dz, r_in + 3.5)
    p_in = Manifold.extrude(cs_in, 0.05).rotate((90, 0, 0)).translate((0.0, y_floor + 0.05, z_c))
    p_out = Manifold.extrude(cs_out, 0.6).rotate((90, 0, 0)).translate((0.0, y_floor - dy, z_c))
    return Manifold.batch_hull([p_in, p_out])


def _asym_squircle_section(rx, ry_front, ry_back, p_front=3.6, p_back=4.0, n=72):
    """Smooth asymmetric superellipse horizontal cross-section (`-y` front face, `+y` flatter occiput back)."""
    pts = []
    for k in range(n):
        ang = 2.0 * math.pi * k / n
        ca, sa = math.cos(ang), math.sin(ang)
        p, ry = (p_front, ry_front) if sa < 0.0 else (p_back, ry_back)
        x = rx * math.copysign(abs(ca) ** (2.0 / p), ca)
        y = ry * math.copysign(abs(sa) ** (2.0 / p), sa)
        pts.append((x, y))
    return CrossSection([pts]).hull()


# Universal face zone. Every human head shares this centre-line front depth and edge squareness across the plate zone
# (zb = chin edge of the plate .. brow), so ONE universal face plate follows all of them; gender lives in width, jaw, brow, crown and ears.
FACE_ZONE_PROFILE = [(-4.0, 9.635, 2.367), (-2.5, 10.990, 2.336), (-1.0, 12.323, 2.310), (0.0, 12.841, 2.301), (1.5, 13.379, 2.465), (3.0, 14.031, 2.690), (4.5, 14.699, 2.915), (6.0, 15.408, 3.140), (7.5, 15.692, 3.294), (9.0, 15.624, 3.300), (10.5, 15.558, 3.297), (12.0, 15.343, 3.285), (13.5, 14.937, 3.263), (15.0, 14.313, 3.229)]   # (zb, ryf, pf) sampled from the neutral head
FACE_ZONE_CORE = (-0.5, 10.8)       # blend weight 1 inside (plate chin edge .. brow)
FACE_ZONE_RAMP = (3.0, 3.2)         # smooth hand-over below / above the core


def _smoothstep(t):
    t = max(0.0, min(1.0, t))
    return t * t * (3.0 - 2.0 * t)


def _face_zone_weight(zb):
    lo0, hi0 = FACE_ZONE_CORE
    if zb < lo0:
        return _smoothstep(1.0 - (lo0 - zb) / FACE_ZONE_RAMP[0])
    if zb > hi0:
        return _smoothstep(1.0 - (zb - hi0) / FACE_ZONE_RAMP[1])
    return 1.0


def _face_zone_lookup(zb):
    pts = FACE_ZONE_PROFILE
    if zb <= pts[0][0]:
        return pts[0][1], pts[0][2]
    if zb >= pts[-1][0]:
        return pts[-1][1], pts[-1][2]
    for (z0, r0, p0), (z1, r1, p1) in zip(pts, pts[1:]):
        if z0 <= zb <= z1:
            u = (zb - z0) / (z1 - z0)
            return r0 + (r1 - r0) * u, p0 + (p1 - p0) * u
    return pts[-1][1], pts[-1][2]


def _apply_face_zone(stations, z_bore):
    """Blend each skull station's centre front depth (`ryf`) and front squareness (`pf`) toward the universal face-zone profile."""
    out = []
    for (z, rx, ryf, ryb, pf, pb) in stations:
        zb = z - (z_bore - 2.9)
        w = _face_zone_weight(zb)
        if w > 0.0 and FACE_ZONE_PROFILE:
            r_u, p_u = _face_zone_lookup(zb)
            ryf = ryf + (r_u - ryf) * w
            pf = pf + (p_u - pf) * w
        out.append((z, rx, ryf, ryb, pf, pb))
    return out


def _organic_human_skull(
    z_stud,
    z_jaw,
    z_cheek_top,
    rx_jaw,
    rx_cheek,
    rx_crown=13.5,
    ryf_jaw=15.05,
    ryf_cheek=16.15,
    ryb_cheek=12.45,
    pf_jaw=2.45,
    pf_cheek=3.85,
    pb_cheek=3.40,
    brow_push=0.0,
    z_bore=None,
    return_stations=False,
):
    """Smooth crease-free humanoid skull with a compact 2x1 neck collar (`z = 0..2.85 mm`),
    support-free C1 submental jaw curve (`<= 42 deg`), plush rounded cheeks, flatter occiput, and cosine crown dome."""
    wafers = [
        Manifold.extrude(rrect(25.2, 12.2, 5.95), 0.04).translate((0.0, 0.0, 0.0)),
        Manifold.extrude(rrect(25.8, 12.3, 5.95), 0.04).translate((0.0, 0.0, 0.45)),
    ]
    z0 = 2.85
    rx0, ryf0, ryb0 = 13.40, 7.15, 6.85
    pf0, pb0 = 2.40, 2.45

    stations = [(z0, rx0, ryf0, ryb0, pf0, pb0)]

    # 1. Smooth C1 submental throat-to-chin & jaw curve (`z0 -> z_jaw`, zero horizontal facet rings)
    n_jaw = 14
    for k in range(1, n_jaw + 1):
        u = k / n_jaw
        s_xy = _c1_ramp(u, f=0.22)
        s_p = u * u * (3.0 - 2.0 * u)
        z = z0 + (z_jaw - z0) * u
        rx = rx0 + (rx_jaw - rx0) * s_xy
        ryf = ryf0 + (ryf_jaw - ryf0) * s_xy
        ryb = ryb0 + (ryb_cheek * 0.94 - ryb0) * s_xy
        pf = pf0 + (pf_jaw - pf0) * s_p
        pb = pb0 + (pb_cheek * 0.94 - pb0) * s_p
        stations.append((z, rx, ryf, ryb, pf, pb))

    # 2. Smooth mid-face cheek & temple swell across the universal faceplate (`z_jaw -> z_cheek_top`)
    n_mid = 10
    for k in range(1, n_mid + 1):
        u = k / n_mid
        s = math.sin(u * math.pi * 0.5)
        bump = math.sin(u * math.pi)
        brow_term = brow_push * max(0.0, math.sin(max(0.0, (u - 0.45) / 0.55) * math.pi))
        z = z_jaw + (z_cheek_top - z_jaw) * u
        rx = rx_jaw + (rx_cheek - rx_jaw) * s + 0.18 * bump
        ryf = ryf_jaw + (ryf_cheek - ryf_jaw) * min(1.0, u * 1.45) + brow_term
        ryb = ryb_cheek * 0.94 + ryb_cheek * 0.06 * s
        pf = pf_jaw + (pf_cheek - pf_jaw) * min(1.0, u * 1.35)
        pb = pb_cheek * 0.94 + pb_cheek * 0.06 * s
        stations.append((z, rx, ryf, ryb, pf, pb))

    # 3. Cosine-smoothed upper forehead & crown dome (`z_cheek_top -> z_stud`)
    n_dome = 14
    ryf_top, ryb_top = 7.35, 6.95
    for k in range(1, n_dome + 1):
        t = k / n_dome
        q = math.sin(t * math.pi * 0.5)
        e = math.cos(t * math.pi * 0.5)
        z = z_cheek_top + (z_stud - z_cheek_top) * q
        rx = rx_crown + (rx_cheek - rx_crown) * e
        e_y = e ** 1.5  # front/back narrow faster toward the crown so a 45-deg self-supporting wig or hat vault clears the scalp
        ryf = ryf_top + (ryf_cheek + brow_push * 0.25 - ryf_top) * e_y
        ryb = ryb_top + (ryb_cheek - ryb_top) * e_y
        pf = 2.65 + (pf_cheek - 2.65) * e
        pb = 2.70 + (pb_cheek - 2.70) * e
        stations.append((z, rx, ryf, ryb, pf, pb))

    if return_stations:
        return stations
    if z_bore is not None:
        stations = _apply_face_zone(stations, z_bore)

    for i, (z, rx, ryf, ryb, pf, pb) in enumerate(stations):
        cs = _asym_squircle_section(rx, ryf, ryb, pf, pb, n=72)
        h = 0.04 if i < len(stations) - 1 else 0.06
        zz = z - h if i == len(stations) - 1 else z
        wafers.append(Manifold.extrude(cs, h).translate((0.0, 0.0, zz)))

    return union([Manifold.batch_hull([wafers[i], wafers[i + 1]]) for i in range(len(wafers) - 1)])


# Shared human ear placement. Heights are measured up from the eye line (the head's `z_bore`), so on every human head the ear sits in the same spot
# relative to the face, and the wigs' ear grooves (`EAR_GROOVE`) are cut to one fixed place. Heads differ only in how far the ear stands out and how deep it is.
EAR_Z_PEAK = 1.2    # the widest, most protruding point of the ear, above the eye line
EAR_Z_TOP = 4.4     # rounded top of the ear, above the eye line
EAR_Z_LOW = -4.2    # the lobe blends into the cheek here; the lower flank is a gentle ramp (the head prints neck-down, so it must not overhang past 45 deg)
EAR_Y_MID = 1.8     # ear centre behind the head origin (mm)
EAR_GROOVE_Y = EAR_Y_MID + 0.1     # the wigs' ear groove is centred here ...
EAR_GROOVE_HW = 3.5               # ... and is this wide (half-width at the hem): the ear's half depth (2.9 at most) plus clearance
EAR_FLANK_SLOPE = 0.92   # max outward lean of the ear's underside, mm per mm of height (45 deg is 1.0)


def _skull_half_width(skull, z):
    """Widest |x| of the skull at height z (0 when the skull is not there)."""
    xs = [abs(p[0]) for P in skull.slice(z).to_polygons() for p in P]
    return max(xs) if xs else 0.0


def _human_ears(skull, z_bore, protrude=2.0, hd=2.9, lobe=0.58):
    """Rounded ears at the shared spot: a teardrop that stands `protrude` mm proud of the skull at its peak, narrows to a soft lobe below
    and rounds off above. The outer edge follows the skull's own width, so the ear sits on the head whatever its cheek shape (the old
    ears were placed in absolute mm and nearly vanished on the wide feminine head)."""
    z_lo, z_pk, z_tp = z_bore + EAR_Z_LOW, z_bore + EAR_Z_PEAK, z_bore + EAR_Z_TOP
    zs = [z_lo + (z_pk - z_lo) * k / 9.0 for k in range(10)] + [z_pk + (z_tp - z_pk) * math.sin(0.5 * math.pi * k / 8.0) for k in range(1, 9)]
    rows = []
    x_prev, z_prev = None, None
    for i, z in enumerate(zs):
        if z <= z_pk:
            t = (z - z_lo) / (z_pk - z_lo)
            b = _c1_ramp(t, f=0.30)
            hdz = hd * (lobe + (1.0 - lobe) * b)
        else:
            t = (z - z_pk) / (z_tp - z_pk)
            b = math.sqrt(max(0.0, 1.0 - t * t))
            hdz = hd * (1.0 - 0.45 * t * t)
        hw = _skull_half_width(skull, z - 0.02 if i == len(zs) - 1 else z)
        x_out = hw + protrude * b
        if x_prev is not None:
            x_out = min(x_out, x_prev + EAR_FLANK_SLOPE * (z - z_prev))   # the ear's own underside never leans out past ~43 deg, even where the cheek is already steep
        x_prev, z_prev = x_out, z
        rows.append((z, hw, x_out, hdz))
    wafers = []
    for i, (z, hw, x_out, hdz) in enumerate(rows):
        x_root = hw - 2.6
        ym = EAR_Y_MID + 0.5 * (z - z_pk) / (z_tp - z_lo)
        hdz = max(hdz, 0.9)
        pts = [(x_root, ym - hdz * 0.88), (x_root, ym + hdz * 0.88)]
        for j in range(17):
            ang = -0.5 * math.pi + math.pi * (j / 16.0)
            pts.append((x_root + (x_out - x_root) * (math.cos(ang) ** 0.78), ym + hdz * math.sin(ang)))
        cs = CrossSection([pts], FillRule.NonZero).hull()
        h = 0.04 if i < len(zs) - 1 else 0.06
        zz = z - h if i == len(zs) - 1 else z
        wafers.append(Manifold.extrude(cs, h).translate((0.0, 0.0, zz)))
    ear_r = union([Manifold.batch_hull([wafers[i], wafers[i + 1]]) for i in range(len(wafers) - 1)])
    return ear_r + ear_r.mirror((1.0, 0.0, 0.0))


def _loft_xy_sections(z_and_polys):
    """Loft convex XY polygon stations `(z, pts)` along Z with 0.05 mm overlap for clean boolean union."""
    segs = []
    for i in range(len(z_and_polys) - 1):
        z0, p0 = z_and_polys[i]
        z1, p1 = z_and_polys[i + 1]
        z0_eff = z0 if i == 0 else z0 - 0.05
        w0 = Manifold.extrude(CrossSection([p0], FillRule.NonZero).hull(), 0.05).translate((0.0, 0.0, z0_eff))
        w1 = Manifold.extrude(CrossSection([p1], FillRule.NonZero).hull(), 0.05).translate((0.0, 0.0, z1 - 0.05))
        segs.append(Manifold.batch_hull([w0, w1]))
    return union(segs)


